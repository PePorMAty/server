//
// Пара, в которой одна сторона — известное имя, а другая — оно же с довеском.
//
//   Пакет ПНД (полиэтилен низкого давления)
//   Агрохимикат Азофоска (нитроаммофоска)
//   Порошок политетрафторэтилена (ПТФЭ)
//
// «ПНД» справочник знает, и «полиэтилен низкого давления» тоже — это одна его
// запись. Нового в паре только слово «пакет», а оно не второе имя вещества, а
// изделие из него. «Азофоска — нитроаммофоска» в справочнике уже есть,
// приписан лишь «агрохимикат».
//
// Такие пары выглядят убедительнее всех: счётчики высокие, половина уже
// опознана. А записывать из них нечего, и вредно: вписав «Пакет ПНД»
// написанием полиэтилена, мы объявили бы изделие тем же узлом, что и сырьё.
//
// Общая для обоих добытчиков — реестрового и графового: вопрос один и тот же,
// и решаться он должен одинаково.

const {
  normalizeName,
  foldLookalikes,
  words,
  stemWord,
} = require("../../routes/industry/utils/normalize");
const { identify } = require("../../routes/industry/utils/synonyms");

/** Набор усечённых слов: «политетрафторэтилена» и «…этилен» — одно слово. */
function stems(text) {
  return new Set(words(foldLookalikes(normalizeName(text))).map(stemWord));
}

/**
 * Написание справочника, которым одна сторона пары уже покрыта, или null.
 *
 * Срабатывает, только когда опознана РОВНО одна сторона: обе опознанные
 * одним веществом — это «справочник уже знает», разными — подозрительная
 * пара, которую человеку надо видеть.
 *
 * Надмножество строгое. «Натр едкий» против «Едкий натр» — те же слова в
 * другом порядке, и это законное второе написание: справочник его не знает,
 * а реестр пишет именно так. Отсеиваем только ЛИШНИЕ слова, а не порядок.
 */
function knownPlusExtra(head, alt) {
  const a = identify(head);
  const b = identify(alt);
  if (a && b) return null;
  const hit = a ?? b;
  if (!hit) return null;

  const other = stems(a ? alt : head);
  for (const spelling of hit.spellings) {
    const own = stems(spelling);
    if (!own.size || own.size >= other.size) continue;
    if ([...own].every((w) => other.has(w))) return spelling;
  }
  return null;
}

module.exports = { knownPlusExtra };
