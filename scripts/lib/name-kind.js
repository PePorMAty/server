//
// Что за название стоит на узле графа: вещество, поток или класс.
//
// Зачем. Список «не знает никто» — 365 строк вперемешку: тут и
// «1,3-Диизопропилбензол», который надо дописать в справочник, и «Побочные
// потоки FCC», которых нет и не будет ни в одной базе, и «Ноутбук». Работы
// там на сотню строк, а выглядит как на триста шестьдесят пять, и за этим
// видом не разглядеть, с чего начинать.
//
// Разметка грубая и намеренно такая: точной её не сделать — границы размыты
// («Жидкая ртуть (Hg)» и вещество, и описание), а угадывать тоньше значило бы
// врать увереннее. Правило безопасности одно: что не опознано, идёт в
// КАНДИДАТЫ. Лишняя строка в списке работы стоит минуты внимания, а вещество,
// молча убранное в «не наше», не вернётся никогда.

const { normalizeName, words } = require("../../routes/industry/utils/normalize");

/**
 * Потоки, фракции и всё, что названо местом в схеме, а не составом.
 *
 * «Побочный поток парового крекинга», «Вакуумный остаток», «деэтанизаторные
 * днища» — у них нет и не может быть ни номера CAS, ни записи в реестре: это
 * не вещество, а то, что течёт по трубе между аппаратами. Состав у него свой
 * на каждом заводе и меняется по ходу работы.
 */
const STREAM = [
  "поток", "потоки", "потоков", "фракция", "фракции", "фракций", "остаток",
  "остатки", "дистиллят", "дистилляты", "газойль", "газойли", "реформат",
  "нафта", "нафты", "нафтовый", "нафтовая", "нафтяная", "днища", "конденсат",
  "конденсаты", "отход", "отходы", "промывные", "продувочные", "пурж",
  "срез", "газ", "газы", "смесь", "смеси", "рассол", "рассолы", "экстракт",
];

/**
 * Сырьё и руды: природный материал, а не продукт химии.
 *
 * «Сахарная свёкла», «Молибденитовый концентрат», «Каменный уголь» — вещи
 * настоящие и называются точно, но реестр ПП №719 и номера CAS про другое.
 */
const RAW = [
  "руда", "руды", "рудный", "концентрат", "концентраты", "уголь", "щепа",
  "свёкла", "свекла", "тростник", "зерно", "зерновые", "шрот", "жмых",
  "залежи", "глина", "глинистый", "сырьё", "сырье", "сырьевые", "пек",
  "биомасса",
];

/**
 * Изделия и материалы, названные назначением.
 *
 * «Смазки для прокатного цеха», «Материнская плата» — назначение вместо
 * вещества. Справочник веществ им не поможет: то же масло под десятком
 * применений даст десять строк и ни одного совпадения.
 */
const GOODS = [
  "смазка", "смазки", "смазочное", "смазочный", "присадка", "присадки",
  "носитель", "наполнитель", "жидкость", "жидкости", "материал", "материалы",
  "компонент", "компоненты", "прекурсор", "прекурсоры", "источник",
  "источники", "загуститель", "эмульгатор", "эмульгаторы", "плата", "модуль",
  "корпус", "батарея", "ноутбук", "частицы", "наночастицы", "аэрогель",
  "премиксы", "комбикорм", "буферы", "микроэлементы",
];

/**
 * Биоматериалы и лабораторные образцы.
 *
 * «Мастер-семенной лот», «Фетальная бычья сыворотка», «Назофарингеальный
 * мазок» — биотехнологические графы. Это не химические вещества, и ни ГИСП,
 * ни CAS про них не знают.
 */
const BIO = [
  "культура", "среда", "мазок", "тампон", "лот", "банк", "изолят", "образец",
  "сыворотка", "инокулят", "вирус", "кровь", "клеточная", "клеточный",
  "мицелия", "штамма", "продуцента", "ферментационная",
];

/**
 * Слова-классы: множественное число говорит о группе веществ, а не об одном.
 *
 * «Полиолы», «Тиолы», «Аммонийные соли», «Эфиры ЖК» — класс соединений.
 * В реестре их нет и не будет: завод заявляет конкретный продукт, а не класс.
 * Правило отбора (onlyClass в store.js) их и так никогда не подтверждает —
 * значит, и работой они не являются.
 */
const CLASS_TAIL =
  /(олы|алы|ены|ины|аны|иды|аты|иты|оны|эфиры|кислоты|спирты|соли|оксиды|амины|силаны|силоксаны|олефины|каучуки|смолы|сульфаты|сульфонаты|галогениды)$/;

const set = (list) => new Set(list);
const STREAM_SET = set(STREAM);
const RAW_SET = set(RAW);
const GOODS_SET = set(GOODS);
const BIO_SET = set(BIO);

/** Виды, в которые раскладывается название. */
const KINDS = {
  substance: "вещество",
  stream: "поток",
  raw: "сырьё",
  goods: "изделие",
  bio: "биоматериал",
  klass: "класс",
};

/**
 * Второе имя в скобке — готовая пара для справочника.
 *
 * «н-бутиральдегид (n-butyraldehyde)», «Соль (NaCl)», «Жидкая ртуть (Hg)» —
 * внутри скобки английское имя, формула или расшифровка. Это тот же материал,
 * что mine-gisp-synonyms добывает из реестра, только лежащий в своих же
 * графах. Длинную скобку не считаем: там уже не имя, а пояснение.
 */
function parenName(name) {
  const m = /\(([^)]{2,40})\)/.exec(String(name ?? ""));
  if (!m) return null;
  const inner = m[1].trim();
  // Скобка с целым предложением — это описание, а не имя.
  if (words(normalizeName(inner)).length > 4) return null;
  return inner;
}

/**
 * Чем название выглядит.
 *
 * Порядок проверок не случаен: «Промывные воды» — множественное число, но
 * прежде всего поток; «Сульфидные концентраты» — сырьё, а не класс сульфидов.
 * Поэтому потоки и сырьё смотрим раньше классов.
 */
function nameKind(rawName) {
  // Судим по имени БЕЗ скобки. Скобка поясняет, а не называет, и её слова
  // уводили вид не туда: «Натриевый хлорид (NaCl, рассол)» уезжал в потоки
  // из-за «рассола», «Пропилен (пропен-содержащий углеводородный поток)» —
  // из-за «потока». Оба — вещества, и оба надо дописать в справочник.
  const ws = words(normalizeName(String(rawName).replace(/\(.*?\)/g, " ")));
  if (!ws.length) return "substance";

  const has = (s) => ws.some((w) => s.has(w));
  // Порядок не случаен: «Ферментационная культура (микробная биомасса)» —
  // биоматериал, хотя «биомасса» стоит и в сырье; «Промывные воды» — поток,
  // хотя множественное число намекает на класс.
  if (has(STREAM_SET)) return "stream";
  if (has(BIO_SET)) return "bio";
  if (has(RAW_SET)) return "raw";
  if (has(GOODS_SET)) return "goods";

  // Класс — по ПОСЛЕДНЕМУ значимому слову: «Жирные спирты» класс, а
  // «Спиртовой раствор» нет.
  const tail = ws[ws.length - 1];
  if (tail && CLASS_TAIL.test(tail)) return "klass";

  return "substance";
}

module.exports = { nameKind, parenName, KINDS };
