//
// Что за название стоит на узле графа: вещество, поток или класс.
//
// Зачем. Список «не знает никто» — 365 строк вперемешку: тут и
// «1,3-Диизопропилбензол», который надо дописать в справочник, и «Побочные
// потоки FCC», которых нет и не будет ни в одной базе, и «Ноутбук». Работы
// там на сотню строк, а выглядит как на триста шестьдесят пять, и за этим
// видом не разглядеть, с чего начинать.
//
// Разметка грубая и намеренно такая: точной её не сделать — границы размыты
// («Жидкая ртуть (Hg)» и вещество, и описание), а угадывать тоньше значило бы
// врать увереннее. Правило безопасности одно: что не опознано, идёт в
// КАНДИДАТЫ. Лишняя строка в списке работы стоит минуты внимания, а вещество,
// молча убранное в «не наше», не вернётся никогда.

const { normalizeName, words } = require("../../routes/industry/utils/normalize");

/**
 * Потоки, фракции и всё, что названо местом в схеме, а не составом.
 *
 * «Побочный поток парового крекинга», «Вакуумный остаток», «деэтанизаторные
 * днища» — у них нет и не может быть ни номера CAS, ни записи в реестре: это
 * не вещество, а то, что течёт по трубе между аппаратами. Состав у него свой
 * на каждом заводе и меняется по ходу работы.
 */
const STREAM = [
  "поток", "потоки", "потоков", "фракция", "фракции", "фракций", "остаток",
  "остатки", "дистиллят", "дистилляты", "газойль", "газойли", "реформат",
  "нафта", "нафты", "нафтовый", "нафтовая", "нафтяная", "днища", "конденсат",
  "конденсаты", "отход", "отходы", "промывные", "продувочные", "пурж",
  "срез", "газ", "газы", "смесь", "смеси", "рассол", "рассолы",
  // «Многокомпонентная продукция скважины» — это поток, а не класс, хотя
  // «скважины» и кончается по-классовому.
  "скважина", "скважины", "скважинный",
  // «Экстракт» сюда НЕ идёт намеренно: «Первичный дистиллятный ароматический
  // экстракт» — поток, а «Кукурузный экстракт» — сырьё, и одним словом их не
  // развести. Спорное уходит в кандидаты — правило безопасности.
];

/**
 * Сырьё и руды: природный материал, а не продукт химии.
 *
 * «Сахарная свёкла», «Молибденитовый концентрат», «Каменный уголь» — вещи
 * настоящие и называются точно, но реестр ПП №719 и номера CAS про другое.
 */
const RAW = [
  "руда", "руды", "рудный", "концентрат", "концентраты", "уголь", "щепа",
  "свёкла", "свекла", "тростник", "зерно", "зерновые", "шрот", "жмых",
  "залежи", "глина", "глинистый", "сырьё", "сырье", "сырьевые", "пек",
  "биомасса",
];

/**
 * Изделия и материалы, названные назначением.
 *
 * «Смазки для прокатного цеха», «Материнская плата» — назначение вместо
 * вещества. Справочник веществ им не поможет: то же масло под десятком
 * применений даст десять строк и ни одного совпадения.
 */
const GOODS = [
  "смазка", "смазки", "смазочное", "смазочный", "присадка", "присадки",
  "носитель", "наполнитель", "жидкость", "жидкости", "материал", "материалы",
  "компонент", "компоненты", "прекурсор", "прекурсоры", "источник",
  "источники", "загуститель", "эмульгатор", "эмульгаторы", "плата", "модуль",
  "корпус", "батарея", "ноутбук", "частицы", "наночастицы", "аэрогель",
  "премиксы", "комбикорм", "буферы", "микроэлементы",
  // Готовые препараты — тоже названы назначением. Сняты с реестра: там после
  // них в скобке СОСТАВ или марка, а не второе имя — «Средство
  // дезинфицирующее ОЗАЛИЗ (изопропанол)», «Клей силикатный (Офис Маг)».
  // «Гель» сюда НЕ идёт: «Гель кремниевой кислоты» — это силикагель.
  "средство", "средства", "реагент", "реагенты", "набор", "имитатор",
  "дезинфектор", "клей",
];

/**
 * Биоматериалы и лабораторные образцы.
 *
 * «Мастер-семенной лот», «Фетальная бычья сыворотка», «Назофарингеальный
 * мазок» — биотехнологические графы. Это не химические вещества, и ни ГИСП,
 * ни CAS про них не знают.
 */
const BIO = [
  "культура", "среда", "мазок", "тампон", "лот", "банк", "изолят", "образец",
  "сыворотка", "инокулят", "вирус", "кровь", "клеточная", "клеточный",
  "мицелия", "штамма", "продуцента", "ферментационная",
];

/**
 * Слова-классы: множественное число говорит о группе веществ, а не об одном.
 *
 * «Полиолы», «Тиолы», «Аммонийные соли», «Эфиры ЖК» — класс соединений.
 * В реестре их нет и не будет: завод заявляет конкретный продукт, а не класс.
 * Правило отбора (onlyClass в store.js) их и так никогда не подтверждает —
 * значит, и работой они не являются.
 */
const CLASS_TAIL =
  /(олы|алы|ены|ины|аны|иды|аты|иты|оны|эфиры|кислоты|спирты|соли|оксиды|амины|силаны|силоксаны|олефины|каучуки|смолы|сульфаты|сульфонаты|галогениды)$/;

/**
 * Окончания прилагательного. Та же мерка, что у isQualifierOnly в
 * normalize.js: имя вещества — существительное, определение — нет. «-ий»
 * сюда не входит по той же причине: магний, кремний, алюминий.
 */
const QUALIFIER_END = /(ый|ая|ое|ые|ой|ую|ым|ых|яя|ее|юю|ого|его|ому|ему)$/;

const set = (list) => new Set(list);
const STREAM_SET = set(STREAM);
const RAW_SET = set(RAW);
const GOODS_SET = set(GOODS);
const BIO_SET = set(BIO);

/** Виды, в которые раскладывается название. */
const KINDS = {
  substance: "вещество",
  stream: "поток",
  raw: "сырьё",
  goods: "изделие",
  bio: "биоматериал",
  klass: "класс",
};

/**
 * Второе имя в скобке — готовая пара для справочника.
 *
 * «н-бутиральдегид (n-butyraldehyde)», «Соль (NaCl)», «Жидкая ртуть (Hg)» —
 * внутри скобки английское имя, формула или расшифровка. Это тот же материал,
 * что mine-gisp-synonyms добывает из реестра, только лежащий в своих же
 * графах. Длинную скобку не считаем: там уже не имя, а пояснение.
 */
function parenName(name) {
  const m = /\(([^)]{2,40})\)/.exec(String(name ?? ""));
  if (!m) return null;
  const inner = m[1].trim();
  // Скобка с целым предложением — это описание, а не имя.
  if (words(normalizeName(inner)).length > 4) return null;
  return inner;
}

/**
 * Чем название выглядит.
 *
 * Порядок проверок не случаен: «Промывные воды» — множественное число, но
 * прежде всего поток; «Сульфидные концентраты» — сырьё, а не класс сульфидов.
 * Поэтому потоки и сырьё смотрим раньше классов.
 */
function nameKind(rawName) {
  // Судим по имени БЕЗ скобки. Скобка поясняет, а не называет, и её слова
  // уводили вид не туда: «Натриевый хлорид (NaCl, рассол)» уезжал в потоки
  // из-за «рассола», «Пропилен (пропен-содержащий углеводородный поток)» —
  // из-за «потока». Оба — вещества, и оба надо дописать в справочник.
  const ws = words(normalizeName(String(rawName).replace(/\(.*?\)/g, " ")));
  if (!ws.length) return "substance";

  const has = (s) => ws.some((w) => s.has(w));
  // Порядок не случаен: «Ферментационная культура (микробная биомасса)» —
  // биоматериал, хотя «биомасса» стоит и в сырье; «Промывные воды» — поток,
  // хотя множественное число намекает на класс.
  if (has(STREAM_SET)) return "stream";
  if (has(BIO_SET)) return "bio";
  if (has(RAW_SET)) return "raw";
  if (has(GOODS_SET)) return "goods";

  // Класс — по ПОСЛЕДНЕМУ значимому слову: «Жирные спирты» класс, а
  // «Спиртовой раствор» нет.
  const tail = ws[ws.length - 1];
  if (tail && CLASS_TAIL.test(tail)) return "klass";

  return "substance";
}

/**
 * Слова, по которым имя опознаётся как химическое.
 *
 * Класс соединения прямо в названии — самый надёжный признак: «карбонат
 * кальция», «серная кислота», «гидроксид натрия».
 *
 * Хладоны, фреоны и галоны — названия хладагентов с номером вместо имени:
 * «Хладон 114В2 (галон 2402)». Раньше их держало правило «буква и цифра»,
 * снятое ниже, и без этих слов верная пара ушла бы в отсев.
 */
const CHEM_WORD =
  /(кислот|ангидрид|оксид|гидроксид|пероксид|сульфат|сульфид|сульфит|хлорид|фторид|бромид|иодид|нитрат|нитрит|карбонат|фосфат|силикат|ацетат|формиат|спирт|эфир|амин|амид|имид|кетон|альдегид|фенол|каучук|полимер|смола|смолы|силан|силоксан|гликол|олефин|парафин|углеводород|щелочь|щёлочь|сода|натр|аммиак|бензол|толуол|ксилол|этилен|пропилен|бутилен|метан|этан|пропан|бутан|хладон|фреон|галон)/i;

/**
 * Приставки химической номенклатуры.
 *
 * «Поли-», «нитро-», «изо-» и прочие стоят в начале имени вещества и почти
 * никогда — в начале названия товара. Список короткий намеренно: «мета-»,
 * «орто-» и «пара-» сюда НЕ идут, они съедают «металлургический» и
 * «параметр», а пишутся обычно через дефис и ловятся не этим.
 *
 * «Тетра-» без «тетрадей»: «Тетради общие на скрепке (скобе)» проходили за
 * химию. Тетрадекан и тетрадецил («тетрадек-», «тетрадец-») остаются.
 */
const CHEM_PREFIX =
  /^(поли|нитро|хлор|фтор|бром|амино|тио|алкил|арил|фенил|метил|этил|пропил|бутил|винил|ацетил|бензил|циклогекс|дихлор|тетра(?!д(?!е[кц]))|гекса|пента)/i;

/** Символы элементов — все 118. */
const ELEMENTS = new Set(
  (
    "H He Li Be B C N O F Ne Na Mg Al Si P S Cl Ar K Ca Sc Ti V Cr Mn Fe Co " +
    "Ni Cu Zn Ga Ge As Se Br Kr Rb Sr Y Zr Nb Mo Tc Ru Rh Pd Ag Cd In Sn Sb " +
    "Te I Xe Cs Ba La Ce Pr Nd Pm Sm Eu Gd Tb Dy Ho Er Tm Yb Lu Hf Ta W Re " +
    "Os Ir Pt Au Hg Tl Pb Bi Po At Rn Fr Ra Ac Th Pa U Np Pu Am Cm Bk Cf Es " +
    "Fm Md No Lr Rf Db Sg Bh Hs Mt Ds Rg Cn Nh Fl Mc Lv Ts Og"
  ).split(" "),
);

/**
 * Формула из НАСТОЯЩИХ символов элементов: «NaCl», «H2SO4», «Ca(OH)2».
 *
 * isElementFormula из normalize.js проверяет только вид — заглавная, иногда
 * строчная, иногда цифры, — и ей этого хватает: она решает, что скобка в
 * подписи узла пересказывает название. А здесь вид обманывает: артикул
 * «Lo416984» и слово «WASH» выглядят формулой, и отсеять их можно, только
 * сверив символы с таблицей. Трогать ту функцию нельзя — на ней стоит
 * сопоставление с реестром.
 */
function isRealFormula(text) {
  const bare = String(text ?? "").replace(/\s+/g, "");
  if (!bare || !/^[A-Za-z0-9()]+$/.test(bare)) return false;
  let depth = 0;
  // Строчная не может начинать символ, поэтому разбор однозначен: заглавная
  // со строчной — это двухбуквенный символ или ничего.
  for (const m of bare.matchAll(/([A-Z][a-z]?)\d*|\(|\)\d*|(.)/g)) {
    if (m[2]) return false;
    if (m[0] === "(") depth += 1;
    else if (m[0].startsWith(")")) {
      depth -= 1;
      if (depth < 0) return false;
    } else if (!ELEMENTS.has(m[1])) return false;
  }
  return depth === 0;
}

/**
 * Похоже ли имя на химическое.
 *
 * Положительный признак, а не чёрный список: в реестре 162 тысячи записей, и
 * товарных категорий там кратно больше, чем веществ. Перечислять их («пакеты»,
 * «блокноты», «плитки», «фитинги») — работа без конца, а признак «это похоже
 * на вещество» короток и проверяем.
 *
 * ОШИБАЕМСЯ ЗДЕСЬ В ДРУГУЮ СТОРОНУ, чем в разметке отчёта, и намеренно. Там
 * потерянное вещество не вернётся, поэтому спорное идёт в работу. Здесь же
 * список кандидатов в полторы тысячи строк никто не станет читать вовсе, и
 * потерянная пара восстановима руками, а утонувшая — нет.
 */
function looksChemical(name) {
  const text = String(name ?? "");
  // Формула целиком: «NaCl», «Hg», «H2SO4» да, кириллические сокращения
  // товаров «РВД» и «ЦСП» нет.
  if (isRealFormula(text)) return true;
  // Формула ВНУТРИ названия: «Натрий хлористый NaCl». Токен обязан нести
  // цифру или строчную — иначе формулами стали бы «PP», «CO» и одинокое «B».
  //
  // Раньше здесь была «буква и цифра» с кириллицей вместе — ради марок вроде
  // «ПЭ100». На живом реестре она пропускала всё подряд: «Конверт С4
  // (324х229)», «Зеркало настенное НБ56», «Отвод (12Х18Н10Т)», «Пруток ХН60ВТ»
  // — артикулы и марки стали, больше сотни строк. А марка полимера рядом с
  // химическим словом ловится и так: «Полиэтилен (ПЭ100)».
  const tokens = text.split(/[\s,;/]+/).filter(Boolean);
  if (tokens.some((t) => /[\da-z]/.test(t) && isRealFormula(t))) return true;
  if (CHEM_WORD.test(text)) return true;
  // Приставка считается только у существительного: «полиэтилен» — вещество,
  // а «полированного» — прилагательное, поймавшееся на «поли». Проверено на
  // живом выводе: «Изделия из полированного алебастра» иначе проходили.
  return words(normalizeName(text)).some(
    (w) => w.length > 5 && CHEM_PREFIX.test(w) && !QUALIFIER_END.test(w),
  );
}

module.exports = { nameKind, parenName, looksChemical, KINDS };
