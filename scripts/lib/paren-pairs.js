//
// Пара «имя — второе имя» из скобки.
//
// Приём один на два источника. В реестре ГИСП второе имя вещества сплошь и
// рядом стоит в скобке сразу за первым — «Изопропилбензол (кумол) Марка А», —
// и то же самое делает модель, называя узлы графа: «Соль (NaCl)»,
// «н-бутиральдегид (n-butyraldehyde)».
//
// Правила отсева жили в mine-gisp-synonyms.js, и каждое куплено ошибкой (см.
// комментарии ниже). Держать их во втором экземпляре значило бы дать им
// разойтись — на этой неделе так уже разъезжались проверка «эти двое связаны»
// и список подписей-заготовок. Поэтому они здесь, а скрипты только говорят,
// что им нужно.

const {
  normalizeName,
  foldLookalikes,
  words,
  stemName,
} = require("../../routes/industry/utils/normalize");

const key = (s) => foldLookalikes(normalizeName(s));

/** Число с единицей: «360 г/л», «5%». Значит, в скобке состав, а не имя. */
const QUANTITY = /\d[\d.,]*\s*(?:%|мг|мкг|кг|мл|г\/л|г|л|моль|ppm|шт|уп)(?![а-яёa-z])/i;

/**
 * Начала, после которых в скобке не имя, а уточнение.
 *
 * «(кроме …)», «(в том числе …)», «(для …)», «(марка А)» — всё это про то же
 * вещество, но синонимом не является: подставив такое в справочник, мы
 * объявили бы «марка А» именем продукта.
 *
 * Конец слова стережём заглядыванием, а не `\b`: в JavaScript граница слова
 * считается по латинице и на кириллице не срабатывает. Без этого «из»
 * съедало «ИЗопропиловый спирт», «при» — «ПРИродный газ», «тип» — «ТИПовой».
 */
const NOT_A_NAME = new RegExp(
  "^(?:" +
    [
      "кроме", "включая", "в\\s+том\\s+числе", "для", "из", "с", "со", "без",
      "не", "по", "при", "согласно", "марка", "марки", "сорт", "тип", "класс",
      "гост", "ту", "артикул", "далее", "см", "например", "напр",
    ].join("|") +
    ")(?![а-яёa-z])",
  "i",
);

/**
 * Одинокое прилагательное: «сжиженный», «вторичный», «технический».
 *
 * Именем вещества оно не бывает — названия в химии существительные. А в
 * скобке такое слово стоит сплошь и рядом: «Газ природный (сжиженный)»,
 * «Полиэтилен (вторичный)». Приняв его за синоним, мы объявили бы сжиженный
 * газ тем же продуктом, что и обычный, и слили бы их в один узел.
 */
const LONE_ADJECTIVE = /^[а-яё-]+(ый|ий|ой|ая|яя|ое|ее|ые|ие)$/i;

/**
 * Союз внутри скобки: там перечисление или пояснение, а не второе имя.
 *
 * «Нитрующая смесь (азотная и серная кислоты)» — это СОСТАВ, две разные
 * кислоты. «Сложные эфиры полиолов (пентаэритритоловые или TMP-эфиры)» —
 * пояснение. Приняв такое за синоним, мы объявили бы серную кислоту тем же
 * веществом, что и азотную.
 *
 * Границу слова стережём заглядыванием по обе стороны: «и» внутри слова
 * встречается в каждом втором названии.
 */
const HAS_CONJUNCTION = /(^|[\s,;])(и|или)([\s,;]|$)/i;

/** Слова, которые сами по себе именем вещества не бывают. */
const JUNK = new Set([
  "прочие", "прочая", "прочий", "прочее", "другие", "остальные",
  "модификация", "исполнение", "вариант", "аналог", "серия", "партия",
]);

/**
 * Разбить перечисление в скобке, не разрывая числа.
 *
 * Запятая в скобке обычно разделяет имена — «(изопропиловый спирт,
 * изопропанол)». Но в химических названиях она же стоит ВНУТРИ имени:
 * «1,2-диметилбензол», «пропандиол-1,2». Наивное деление давало
 * «2-диметилбензол» — имя несуществующего вещества.
 */
function splitNames(inner) {
  const GUARD = "\u0001";
  return inner
    .replace(/(\d)\s*,\s*(\d)/g, `$1${GUARD}$2`)
    .split(/[;,]/)
    .map((p) => p.split(GUARD).join(","));
}

/**
 * Разобрать название на пары «головное имя — второе имя».
 *
 * Берём ТОЛЬКО скобку, стоящую сразу за именем, не дальше третьего значимого
 * слова. Дальше по названию скобка означает уже не второе имя, а торговую
 * марку, наполнитель или количество — это выяснилось на замере совпадений:
 * «…концентрации этанола в крови (ЭТАНОЛ-ОЛЬВЕКС)» синонимом этанола не
 * является ни в каком смысле.
 *
 * @param {string} rawName название целиком
 * @param {object} [opts]
 * @param {boolean} [opts.allowLatin] брать ли второе имя, написанное одной
 *   латиницей. Для РЕЕСТРА — нет: там латиница почти всегда торговое имя или
 *   артикул. Для ГРАФОВ — да, и это главная добыча: «Соль (NaCl)», «Жидкая
 *   ртуть (Hg)», «Амфотерицин B (Amphotericin B)». Разница между источниками
 *   ровно в этом, и потому она — параметр, а не второй экземпляр правил.
 * @param {number} [opts.minAlt] короче скольких знаков второе имя не берём.
 *   По умолчанию 3, как было у реестра: двухбуквенные «ЖК» и «СО» там ловушки.
 *   Графам нужно 2 — ради формул «Hg», «Ca».
 */
function parenPairs(rawName, opts = {}) {
  const minAlt = opts.minAlt ?? 3;
  const text = String(rawName ?? "").trim();
  const open = text.indexOf("(");
  if (open < 2) return [];
  // Ищем ПАРНУЮ закрывающую, считая вложенность. Первая попавшаяся ломала
  // разбор на вложенных скобках: «Синтетические диэстеры (ди(изооктил)адипат
  // /себацинат)» давало второе имя «ди(изооктил» — обрывок.
  let depth = 0;
  let close = -1;
  for (let i = open; i < text.length; i++) {
    if (text[i] === "(") depth += 1;
    else if (text[i] === ")") {
      depth -= 1;
      if (depth === 0) {
        close = i;
        break;
      }
    }
  }
  if (close < 0) return [];

  // Скобка ВНУТРИ имени, а не после него: так устроена химическая
  // номенклатура — «Метил 2-(диметилдитиофосфато)ацетат», «ди(изооктил)
  // адипат». Признак точный: сразу за закрывающей идёт буква, без пробела.
  // Без этой проверки из первого получалась пара «Метил 2- | диметил-
  // дитиофосфато» — два обрывка, ни один из которых не вещество.
  if (/^[0-9a-zа-яё-]/i.test(text.slice(close + 1))) return [];

  const head = text.slice(0, open).trim().replace(/[,;:]+$/, "");
  const inner = text.slice(open + 1, close).trim();
  // Длина скобки — по той же мерке, что и каждого имени внутри: иначе
  // двухбуквенная формула «(Hg)» отсеивалась бы ещё до разбора.
  if (head.length < 3 || inner.length < minAlt) return [];

  const headWords = words(stemName(head));
  if (!headWords.length || headWords.length > 3) return [];
  if (QUANTITY.test(inner) || NOT_A_NAME.test(inner)) return [];
  if (headWords.some((w) => JUNK.has(w))) return [];

  const out = [];
  for (const part of splitNames(inner)) {
    const alt = part.trim().replace(/^["'«»]+|["'«»]+$/g, "");
    if (alt.length < minAlt) continue;
    const altWords = words(stemName(alt));
    if (!altWords.length || altWords.length > 3) continue;
    if (altWords.some((w) => JUNK.has(w))) continue;
    if (NOT_A_NAME.test(alt)) continue;
    // Своя скобка внутри второго имени — значит, это не имя, а разбор с
    // уточнением: «Кислота (соль (натриевая))». Чистое второе имя скобок
    // не содержит.
    if (/[()]/.test(alt)) continue;
    if (HAS_CONJUNCTION.test(alt)) continue;
    if (LONE_ADJECTIVE.test(alt.trim())) continue;
    if (!opts.allowLatin && !/[а-яё]/i.test(alt)) continue;
    if (key(alt) && key(head) && key(alt) !== key(head)) out.push([head, alt]);
  }
  return out;
}

module.exports = { parenPairs, splitNames, key, QUANTITY, NOT_A_NAME, LONE_ADJECTIVE, JUNK };
