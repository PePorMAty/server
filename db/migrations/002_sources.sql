-- db/migrations/002_sources.sql — этап 2 PG-MIGRATION.md: база источников и
-- расчёты материального баланса.
--
-- Те же таблицы и колонки, что в SQLite (routes/local-sources/utils/store.js,
-- routes/material-balance/utils/store.js): хранилища пишут один SQL на обе
-- базы (db/sql.js), переключатель — SOURCES_STORE=pg. Типы те же, что
-- читает код: время — текстом ISO (его сравнивают строками), признаки —
-- числами 0/1, списки — JSON-текстом.
--
-- PDF документов и копии веб-страниц остаются файлами на диске
-- (data/local-sources/files/, data/material-balance-sources/), в базе —
-- их sha256.
--
-- Номера (id) — identity BY DEFAULT: перенос из SQLite кладёт прежние
-- номера (ссылки на документы и разделы в сохранённых графах — по ним), а
-- новые берутся дальше. Удалённый номер не достаётся новому документу —
-- как AUTOINCREMENT в SQLite.

-- Документ — загруженный PDF.
CREATE TABLE app.documents (
  id          integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  sha256      text NOT NULL UNIQUE,
  file_name   text NOT NULL,
  title       text NOT NULL,
  pages       integer NOT NULL,
  textless    integer NOT NULL DEFAULT 0,
  chars       integer NOT NULL,
  bytes       integer NOT NULL,
  added_at    text NOT NULL,
  added_via   text NOT NULL,
  short_title text,
  structure   text,
  page_offset integer,
  provider    text,
  model       text,
  parsed_at   text
);

-- Раздел документа — запись-источник; status: pending → working → done | failed.
CREATE TABLE app.sections (
  id          integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  doc_id      integer NOT NULL REFERENCES app.documents (id) ON DELETE CASCADE,
  ord         integer NOT NULL,
  number      text,
  title       text NOT NULL,
  full_title  text,
  path        text NOT NULL DEFAULT '',
  page_from   integer NOT NULL,
  page_to     integer NOT NULL,
  text        text NOT NULL,
  status      text NOT NULL DEFAULT 'pending',
  summary     text,
  io          text NOT NULL DEFAULT '[]',
  extracted   text,
  model       text,
  error       text,
  attempts    integer NOT NULL DEFAULT 0,
  claimed_by  integer,
  claimed_at  text,
  decoded_at  text
);
CREATE INDEX sections_doc ON app.sections (doc_id, ord);
CREATE INDEX sections_status ON app.sections (status);

-- Связь раздела с продуктом; key — основы слов названия. seq — порядок
-- вставки (в SQLite — rowid): целевой продукт раздела записан первым, и
-- подписи берутся в этом порядке.
CREATE TABLE app.section_products (
  seq         integer GENERATED ALWAYS AS IDENTITY,
  section_id  integer NOT NULL REFERENCES app.sections (id) ON DELETE CASCADE,
  key         text NOT NULL,
  label       text NOT NULL,
  direction   text NOT NULL CHECK (direction IN ('up', 'down')),
  role        text NOT NULL,
  origin      text NOT NULL,
  PRIMARY KEY (section_id, key, direction)
);
CREATE INDEX section_products_key ON app.section_products (key, direction);
CREATE INDEX section_products_seq ON app.section_products (seq);

-- Служебные отметки базы источников (версия расчёта ключей, разовые чистки);
-- в SQLite — таблица meta.
CREATE TABLE app.sources_meta (
  name  text PRIMARY KEY,
  value text
);

-- Готовые расчёты материального баланса (общие для всех графов).
CREATE TABLE app.balances (
  id            integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  basis_key     text NOT NULL,
  target_key    text NOT NULL,
  tech_key      text NOT NULL,
  basis_label   text NOT NULL,
  target_label  text NOT NULL,
  tech_label    text NOT NULL,
  direction     text NOT NULL DEFAULT 'down',
  status        text NOT NULL,
  answer        text NOT NULL,
  parsed        text NOT NULL,
  refs          text NOT NULL,
  known_data    text NOT NULL DEFAULT '',
  custom_prompt integer NOT NULL DEFAULT 0,
  provider      text,
  model         text,
  took_ms       integer,
  created_at    text NOT NULL,
  kind          text NOT NULL DEFAULT 'pair',
  inputs_key    text NOT NULL DEFAULT '',
  targets_key   text NOT NULL DEFAULT '',
  inputs_label  text NOT NULL DEFAULT '[]',
  targets_label text NOT NULL DEFAULT '[]',
  title         text NOT NULL DEFAULT '',
  basis_amount  text,
  local_key     text NOT NULL DEFAULT ''
);
CREATE INDEX balances_pair ON app.balances (basis_key, target_key);

-- Копии веб-источников расчётов: что и откуда; сами файлы — на диске.
CREATE TABLE app.web_documents (
  id            integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  url           text NOT NULL,
  final_url     text NOT NULL,
  kind          text NOT NULL,
  content_type  text,
  title         text NOT NULL DEFAULT '',
  sha256        text NOT NULL,
  bytes         integer NOT NULL,
  chars         integer NOT NULL,
  fetched_at    text NOT NULL
);
CREATE INDEX web_documents_url ON app.web_documents (url);
