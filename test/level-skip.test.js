// Проверка перепрыгивания уровня (routes/step/utils/levelSkip.js) на
// текстах живых прогонов. Модель не нужна.
//
//   npm test

const { test } = require("node:test");
const assert = require("node:assert/strict");

const { skippedIntermediates, acceptFollowUp } = require("../routes/step/utils/levelSkip");

const answer = (out, inp, desc) => `# Новый производственный шаг

## Шаг

- **Что производят:** [${out}]

- **Из чего производят:** [${inp}]

- **Побочные продукты:** []

- **Описание:** ${desc}

# Альтернативы
`;

// Промежуточные продукты разделов фенола в базе (2026-10-29), без потоков.
const MID = [
  "Циклогексан", "Циклогексанол", "Циклогексанон", "Гидроксиламинсульфат", "Циклогексаноноксим",
  "Целевой алкилфенол", "Сырой алкилфенол", "Алкилфенолят натрия", "Дифенилкарбонат", "Метилфенилкарбонат",
];

test("капролактам мимо циклогексанола и циклогексанона — перепрыгивание", () => {
  const md = answer(
    "Капролактам",
    "Фенол, водород, аммиак, серная кислота, олеум",
    "Фенол гидрируют до циклогексанола, его дегидрируют до циклогексанона, оксим циклогексанона перегруппировывают в капролактам.",
  );
  assert.deepEqual(skippedIntermediates(md, "Фенол", MID), ["Циклогексанол", "Циклогексанон"]);
});

test("«целевой продукт — алкилфенол» — не «Целевой алкилфенол»: слова врозь не в счёт", () => {
  // Первый ответ живого прогона на домене 2026-10-29: верный шаг, а сервер
  // переспросил — и модель ушла в «Алкилат».
  const md = answer(
    "Алкилфенол",
    "Фенол, тримеры пропилена",
    "Фенол алкилируют тримерами пропилена на ионообменной смоле; из алкилата ректификацией выделяется целевой продукт — алкилфенол.",
  );
  assert.deepEqual(skippedIntermediates(md, "Фенол", MID), []);
});

test("уточнённый выход («Целевой алкилфенол» при «Алкилфенол») — не пропущенная ступень", () => {
  const md = answer("Алкилфенол", "Фенол, олигомеры этилена", "Получают целевой алкилфенол из сырого алкилфенола отгонкой.");
  assert.deepEqual(skippedIntermediates(md, "Фенол", MID), []);
});

test("ответ на дозапрос — только названный продукт, не поток", () => {
  const skipped = ["Циклогексанол", "Циклогексанон"];
  assert.equal(acceptFollowUp(answer("Циклогексанон", "Фенол, водород", "…"), skipped), true);
  // Поток, которого сервер не называл, — первый ответ остаётся.
  assert.equal(acceptFollowUp(answer("Алкилат", "Фенол, тримеры пропилена", "…"), skipped), false);
  // Тот же перепрыгнувший выход — тоже нет.
  assert.equal(acceptFollowUp(answer("Капролактам", "Фенол", "…"), skipped), false);
});
