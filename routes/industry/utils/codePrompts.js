const DEFAULT_PROMPTS = { okpd2: OKPD2_PROMPT, tnved: TNVED_PROMPT };

const LEVEL = {
  okpd2: { top: "класс ОКПД2 (код xx)", group: "подгруппу ОКПД2 (код xx.xx)", file: "ОКПД2" },
  tnved: { top: "группу ТН ВЭД (2 цифры)", group: "товарную позицию ТН ВЭД (4 цифры)", file: "ТН ВЭД ЕАЭС" },
};

/**
 * Выбор подгруппы (top: false) или верхнего уровня (top: true) из списка —
 * найденного поиском по названию или всех подгрупп класса.
 */
function groupPrompt(kind, { product, description, candidates, top = false, searched = true }) {
  const what = top ? LEVEL[kind].top : LEVEL[kind].group;
  const list = candidates
    .map((c) => {
      const found = (c.hits ?? []).map((h) => `\n    найдено: ${h.code} ${h.name}`).join("");
      return `${c.code} ${c.name}${found}`;
    })
    .join("\n");
  return [
    `Ты — эксперт по классификатору ${LEVEL[kind].file}. Определи ${what}, к которой относится товар, — только из списка ниже: это фрагмент файла классификатора, ${searched ? "найденный поиском по названию товара и его синонимам (file_search)" : "все варианты этого уровня"}. Не придумывай коды и не выходи за список.`,
    `Товар: «${product}».${description ? `\nОписание товара: ${description}` : ""}`,
    "Выбирай по сущности самого товара — что это за вещество, материал или изделие, — а не по области применения или услугам с ним. Деталь или агрегат изделия («Двигатель (Самолёт)») относится к позиции самой детали для этого изделия, а не к изделию целиком и не к ремонту.",
    `Список:\n${list}`,
    "Окончательный вывод строго: один код из списка или NONE, если ни один не подходит. Без пояснений.",
  ].join("\n\n");
}

/** Описание товара — строкой после названия; пустое — без строки. */
function descriptionLine(description) {
  const d = String(description ?? "").replace(/\s+/g, " ").trim().slice(0, 600);
  return d ? `Product description: ${d}\n` : "";
}

/** Подставить значения в промпт конечного кода (свой или по умолчанию). */
function leafPrompt(kind, template, { product, description, subgroup, fragment }) {
  let text = String(template || DEFAULT_PROMPTS[kind]);
  if (!text.includes("<<<FRAGMENT>>>")) text += `\n\nФрагмент файла классификатора (file_search, ${subgroup}):\n<<<FRAGMENT>>>`;
  if (!text.includes("<<<PRODUCT>>>")) text = `Product name: <<<PRODUCT>>>.\n<<<DESCRIPTION>>>\n${text}`;
  const vars = {
    "<<<PRODUCT>>>": product,
    "<<<DESCRIPTION>>>": descriptionLine(description),
    "<<<SUBGROUP>>>": subgroup,
    "<<<FRAGMENT>>>": fragment,
  };
  for (const [k, v] of Object.entries(vars)) text = text.split(k).join(v);
  return text;
}

module.exports = { DEFAULT_PROMPTS, groupPrompt, leafPrompt, descriptionLine };
