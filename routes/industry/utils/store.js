/**
 * Классы ОКПД2, где выпускают вещества и материалы: добыча (05–08), пищевые
 * продукты и напитки (10–12), волокна и пряжа (13), древесина (16), бумага и
 * целлюлоза (17), нефтепродукты (19), химия (20), фармацевтика (21), резина и
 * пластмассы (22), цемент, известь, стекло (23), металлы (24), энергия и газ
 * (35).
 *
 * Вещество справочника ищется только здесь. В изделиях его название стоит
 * как материал или комплектующее: «Генератор азота мембранный» (28 — машины)
 * для «Азота», «Аккумуляторная батарея с серной кислотой» (27 —
 * электрооборудование) для «Серной кислоты». Отбор по месту слова такие
 * записи пропускает: слово второе и покрывает половину названия. Пока в базе
 * были только сырьевые классы, это было не видно; с машинами, электроникой и
 * одеждой стало бы чужими производителями.
 *
 * Отбор — в самом запросе, а не после: иначе две сотни «генераторов азота»
 * вытеснили бы настоящий азот из выдачи (MAX_ENTRIES_PER_PRODUCT).
 * Продукт, которого справочник не знает («Генератор азота» на графе
 * машиностроения), ищется по всем классам, как и раньше.
 */
const SUBSTANCE_CLASSES = [
  "05", "06", "07", "08", "10", "11", "12", "13", "16", "17",
  "19", "20", "21", "22", "23", "24", "35",
];

/** Условие SQL «запись из класса веществ»; prefix — псевдоним таблицы с точкой. */
function substanceClassSql(prefix = "") {
  const code = `TRIM(${prefix}okpd2)`;
  const list = SUBSTANCE_CLASSES.map((c) => `'${c}'`).join(",");
  return `(${prefix}okpd2 IS NULL OR ${code} = '' OR substr(${code}, 1, 2) IN (${list}))`;
}

/**
 * Ступени лестницы, которым можно доверять чужое написание вещества.
 *
 * Требуют совпадения всех значимых слов. Мягкие ступени («любое из слов»,
 * «по приставке») на синонимах дают ложные попадания и потому применяются
 * только к тому названию, которое спросили.
 */
const STRICT_LEVELS = new Set(["all-words", "core-words"]);

/** Ступени, где совпасть могло одно-единственное слово из запроса. */
const LOOSE_LEVELS = new Set(["partial", "prefix"]);

/**
 * Порядок ступеней — от самой надёжной к самой нечёткой.
 *
 * Перечислен здесь, а не выводится из лестницы: лестница для КАЖДОГО написания
 * своя и не всякая несёт все ступени, а обход идёт по ступеням сразу для всех
 * написаний. Порядок должен быть один и тот же, чем бы ни оказалось первое
 * написание.
 *
 * Ступень, которой здесь нет, не пропадает: она добавляется в конец обхода на
 * месте. Так список остаётся подсказкой о порядке, а не единственным местом,
 * которое надо не забыть поправить.
 */
const LADDER_ORDER = ["all-words", "core-words", "partial", "prefix"];

/**
 * Частота слова в реестре нужна теперь только для объяснения, а не для
 * решения: по ней видно, за что зацепилось мягкое совпадение. Порогом она
 * была недолго и работы не сделала — верные и ложные совпадения по редкости
 * перекрываются (см. комментарий в lookupProduct).
 */

