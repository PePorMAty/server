const PRODUCT_BEFORE = new Set(
  [
    "средство", "средства", "гуашь", "среда", "листы", "пакет", "пакеты", "мешок", "мешки",
    // «Перчатки из полимерной пленки (полиэтилен низкого давления)» — снимок
    // после d15de9c: у полиэтилена низкого давления проходило «вторым именем
    // в скобках», а скобка называет материал плёнки.
    "перчатки",
    // «Чаша PP (полипропилен) BP330» — снимок 2778f2f → d26090d: у
    // полипропилена проходило «вторым именем в скобках». Посуда и тара
    // называют изделие, а скобка после них — материал.
    "чаша", "чаши", "стакан", "стаканы", "емкость", "канистра", "бутылка", "флакон",
    "крышка", "контейнер", "ведро",
  ].map(stemWord),
);

/**
 * Признаки лекарства или медицинского изделия в названии записи: «раствор для
 * инфузий», «для инъекций», «лекарственных форм», «раствор стерильный»,
 * «физиологический», «изотонический», «№ РЗН …» — номер регистрации
 * медизделия в Росздравнадзоре.
 *
 * Сверяем по НАЧАЛУ усечённого слова: усечение даёт разные хвосты —
 * «инфузий» → «инфуз», «инфузии» → «инфузи», а «лекарственных» не усекается
 * вовсе.
 */
const MEDICINE_PREFIXES = ["инфуз", "инъекц", "лекарствен", "стерильн", "физиологическ", "изотоническ"];

const hasMedicineWord = (stems) =>
  stems.some((w) => w === "рзн" || MEDICINE_PREFIXES.some((p) => w.startsWith(p)));

/**
 * Запись — лекарственная форма или медицинское изделие: судим по названию.
 *
 * Код ОКПД2 21.20 («Препараты лекарственные…») признаком НЕ служит, хотя
 * просится. Под ним зарегистрирован медицинский кислород: «Кислород
 * газообразный медицинский», «Кислород жидкий медицинский» — и это не
 * лекарство, в которое кислород входит, а сам кислород. Снимок отнял его у
 * кислорода, пока признаком был код; у хлорида натрия все 22 лекарства
 * узнаются и по словам.
 */
function isMedicine(rowList) {
  return hasMedicineWord(rowList);
}

/**
 * Мочевинный раствор для дизелей: «AUS 32» — его имя по ISO 22241, «AdBlue» —
 * торговая марка. Признаки узкие нарочно: «Карбамид для DEF» — это сам
 * карбамид, сырьё для такого раствора, и отнимать его нельзя.
 */
function isUreaSolution(rowList) {
  for (let i = 0; i < rowList.length; i++) {
    const w = rowList[i];
    if (w === "adblue" || /^aus\d+$/.test(w)) return true;
    if (w === "aus" && /^\d+$/.test(rowList[i + 1] ?? "")) return true;
  }
  return false;
}

/**
 * Коды препаративных форм пестицидов: КЭ — концентрат эмульсии, КС —
 * концентрат суспензии, ВР — водный раствор, СП — смачивающийся порошок,
 * ВДГ — водно-диспергируемые гранулы и так далее, как в Государственном
 * каталоге пестицидов.
 *
 * Однобуквенных (Г, П, Д) и двусмысленных (ВС — «высший сорт», ВК) здесь
 * нет: цена ложного срабатывания выше пользы.
 */
const FORM_CODES = [
  "ВДГ", "ВДК", "ВР", "ВРГ", "ВРК", "ВРП", "ВСК", "ВЭ", "ККР", "КМЭ", "КНЭ",
  "КС", "КЭ", "МД", "МКС", "МКЭ", "МЭ", "РП", "СК", "СП", "СЭ", "ТАБ", "ТКС",
  "ТПС", "ЭМВ",
];
// Код стоит после запятой и замыкает название или идёт перед скобкой:
// «Сера 400, КС (фунгицид)», «Би-58 Новый, КЭ (400 г/л диметоата)». Регистр
// строгий: в реестре коды пишут прописными, а строчные «вр», «сп» бывают и
// обычными сокращениями.
const FORM_CODE_RE = new RegExp(`,\\s*(?:${FORM_CODES.join("|")})\\s*(?=$|[(,;.])`);
// Назначение, названное словом. Только именительный падеж: «Сера для
// производства фунгицидов» — это сама сера, сырьё, а не препарат.
//
// «Десиканта» и «протравителя» нет намеренно: десикант — это и осушитель
// («Силикагель-десикант»), протравитель — и для дерева или металла. Препараты
// для протравки семян и так узнаются по коду формы (КС, ТПС, ВСК).
const PESTICIDE_WORD_RE =
  /(?<![а-яё])(?:пестицид|фунгицид|гербицид|инсектицид|акарицид|инсектоакарицид|дефолиант|родентицид|нематицид|моллюскоцид|фумигант|арборицид)(?![а-яё])/i;

/**
 * Препаративная форма пестицида, названная по действующему веществу:
 * «Сера 400, КС (фунгицид)» — концентрат суспензии, 400 г/л серы.
 *
 * Отбор узнавал препарат только по скобке с дозировкой — «ТОРНАДО, ВР (360
 * г/л глифосата к-ты)». Когда вещество названо в самом имени препарата,
 * запись подтверждалась первым словом как само вещество: «Сера» и
 * «Элементная сера» получали в карточку производителя фунгицида. Решение
 * заказчика то же, что для скобки: препарат засчитывается, только если
 * самого вещества в реестре нет, и помечается отдельно.
 */
function isPesticideForm(name) {
  const text = String(name ?? "");
  return FORM_CODE_RE.test(text) || PESTICIDE_WORD_RE.test(text);
}

/**
 * Приставки положения: о-, м-, п-, орто-, мета-, пара-.
 *
 * С ними одно слово называет РАЗНЫЕ вещества: «Ксилол» — смесь изомеров, а
 * «О-Ксилол» — один из них, и в справочнике это разные записи. Однобуквенная
 * приставка при сверке отпадает (слова короче двух букв не считаются), и
 * запись «О-Ксилол (1,2-диметилбензол) химически чистый» подтверждала
 * «Ксилол» первым словом — снимок 2778f2f → d26090d.
 */
const ISOMER_MARK =
  /(?<![а-яёa-z0-9])(о|м|п|o|m|p|орто|мета|пара|ortho|meta|para|\d+(?:\s*,\s*\d+)*'?)\s*-\s*([а-яёa-z][а-яёa-z0-9]*)/gi;

/**
 * Запись называет изомер, который справочник знает ОТДЕЛЬНЫМ веществом, а
 * спрашивали другое: возвращает написание изомера («О-Ксилол») или null.
 *
 * Решает справочник, а не сама приставка: «п-аминобензойную кислоту» мы
 * отдельно не знаем, и запрос без приставки её по-прежнему находит. А
 * спросили сам изомер — «О-Ксилол», «Орто-ксилол», — и запись его: запрета нет.
 *
 * Приставка бывает и цифрами: у «Ксилола» есть написание «Диметилбензол», и
 * оно совпадало со скобкой «О-Ксилол (1,2-диметилбензол)» как второе имя.
 * «1,2-диметилбензол» справочник знает как о-ксилол — значит, запись не та.
 *
 * Запрос, которого справочник не знает, не судим: неизвестно, какое из
 * веществ спрашивали.
 */
function otherIsomer(name, queryStems, askedCanon, queryMarked = new Set()) {
  if (!askedCanon) return null;
  const text = String(name ?? "");
  // Слова записи, у которых есть приставка, — для обратного случая ниже.
  const markedInRow = new Set();
  for (const m of text.matchAll(ISOMER_MARK)) {
    const word = m[2];
    const stem = stemWord(normalizeName(word));
    markedInRow.add(stem);
    if (!queryStems.has(stem)) continue;
    const isomer = identify(`${m[1]}-${word}`)?.canon;
    if (isomer && isomer !== askedCanon) return `${m[1]}-${word}`;
  }

  // Обратный случай: спросили изомер — «м-Ксилол», — а в записи то же слово
  // без приставки: «Ксилол нефтяной». Снимок d26090d → 01dbd59: у мета- и
  // пара-ксилола оставались записи смеси изомеров. Справочник знает голое
  // слово ДРУГИМ веществом — значит, запись не про спрошенный изомер.
  for (const stem of queryMarked) {
    if (markedInRow.has(stem)) continue;
    const bare = normalizeName(text)
      .split(" ")
      .find((w) => w && stemWord(w) === stem);
    if (!bare) continue;
    // Номер ПОСЛЕ слова — «Бутандиол-1,4» — та же приставка, только сзади.
    const escaped = bare.replace(/[.*+?^${}()|[\]\\]/g, "\\$&");
    if (new RegExp(`(?<![а-яёa-z])${escaped}\\s*-\\s*\\d`, "i").test(text)) continue;
    const other = identify(bare)?.canon;
    if (other && other !== askedCanon) return bare;
  }
  return null;
}

/** Основы названий классов препаратов — в любом числе и падеже. */
const PESTICIDE_CLASS_STEMS = new Set([
  "пестицид", "фунгицид", "гербицид", "инсектицид", "акарицид", "инсектоакарицид",
  "дефолиант", "родентицид", "нематицид", "моллюскоцид", "фумигант", "арборицид",
  "сзр",
]);

/**
 * Спрашивают о КЛАССЕ препаратов: «Средства защиты растений», «Пестициды»,
 * «Гербициды». Препарат в ответ на такой вопрос — сам ответ, а не вещество
 * в составе.
 *
 * Поймано снимком: узел «Средства защиты растений» (в справочнике рядом с
 * ним «Пестициды») получил пометку «вещество названо в составе препарата» на
 * записях «Пестицид Гардо Голд, СЭ (…)» — а вещества там никто не спрашивал.
 *
 * В отличие от записей реестра, здесь смотрим основы, а не точную форму:
 * класс и называют во множественном числе. Ложного срабатывания бояться
 * нечего — название запроса, в котором стоят «гербициды», и так про них.
 */
function namesPesticideClass(name) {
  const stems = words(stemName(String(name ?? "")));
  if (stems.some((w) => PESTICIDE_CLASS_STEMS.has(w))) return true;
  return stems.includes("средств") && stems.includes("защит") && stems.includes("растен");
}

/**
 * Спрашивают о самом лекарстве — «Физиологический раствор», «Вода для
 * инъекций». Тогда лекарственные записи не второй сорт, а ровно то, что
 * искали.
 */
function isPharmaQuery(spellings) {
  return spellings.some((s) => hasMedicineWord(words(stemName(s))));
}

/**
 * Слова, называющие ФОРМУ, а не вещество: фракция, марка, порошок, раствор.
 *
 * Поймано сравнением снимков после расширения реестра: «Фракция C4»
 * подтверждалась записью «Гравий фракции 80+». Общее слово там ровно одно —
 * «фракция», — и его довольно, чтобы пройти правило «второе слово, треть
 * записи». Фракции бывают у гравия, у калийного удобрения и у перегонки; само
 * по себе это слово не называет вещество, и совпадение по нему одному не
 * доказывает ничего.
 *
 * Список работает ТОЛЬКО в проверке «совпали одни такие слова». Запись, где
 * рядом с формой названо и вещество, он не трогает: «Аммиак водный» совпадает
 * по «аммиаку», а не по «водному», и «раствор» в этом списке ему не мешает.
 * Потому сюда и можно класть широкие слова, которые в запрете по первому слову
 * (SUPPLY_FORM) были бы опасны.
 *
 * Тот же вопрос, что у reference/synonyms-stop.txt: можно ли этим словом
 * назвать два разных продукта на графе? Списки всё же разные — там отменяют
 * синонимы, здесь судят совпадение с реестром, и в стоп-лист попадают ещё и
 * просто ошибочные названия.
 *
 * Хранятся усечённые формы: сравнение идёт по ним же.
 */
const FORM_WORDS = new Set(
  [
    // Нарезка, помол, сортность.
    "фракция", "марка", "сорт", "гранулы", "гранулят", "порошок", "паста",
    "крошка", "брикет", "хлопья", "пудра",
    // Агрегатное состояние и способ подачи.
    "раствор", "смесь", "концентрат", "суспензия", "эмульсия", "жидкость",
    // Слова, которыми называют что угодно.
    "материал", "изделие", "продукт", "состав", "добавка", "реагент",
    "средство", "препарат", "сырьё", "полуфабрикат",
  ].map(stemWord),
);

/**
 * Не про соединение ли эта запись.
 *
 * Возвращает слово-класс, если оно стоит ВПРИТЫК к совпавшему и в запросе его
 * нет. Соседство важно: в длинном названии слово вроде «сульфат» может
 * оказаться посторонним уточнением, и запрещать по нему всю запись было бы
 * слишком грубо.
 */
function foreignCompound(rowList, queryStems) {
  for (let i = 0; i < rowList.length; i++) {
    if (!queryStems.has(rowList[i])) continue;
    for (const j of [i - 1, i + 1]) {
      const near = rowList[j];
      if (near && COMPOUND_CLASS.has(near) && !queryStems.has(near)) return near;
    }
  }
  return null;
}

/** Сколько слов в скобке ещё считается синонимом, а не составом. */
const SYNONYM_PARENS_WORDS = 4;

/**
 * Число с единицей измерения: «360 г/л», «5%», «200 мл».
 *
 * По нему отличается состав от имени. Одной длины скобки не хватило:
 * «(400 г/л диметоата)» — всего четыре слова, а это концентрация, а не второе
 * название вещества. Просто цифры признаком быть не могут — они сплошь и
 * рядом в самих названиях: «(1,2-диметилбензол)», «(марки ПЭС-1, ПЭС-2)».
 *
 * Конец единицы стережём заглядыванием, а не `\b`: в JavaScript граница слова
 * считается по латинице, и для «г/л» она не срабатывает — кириллическая «л»
 * для `\b` не буква. На этом правило и попалось при проверке.
 */
const QUANTITY_RE =
  /\d[\d.,]*\s*(?:%|мг|мкг|кг|мл|г\/л|г|л|моль|ppm)(?![а-яёa-z])/i;

/**
 * Сколько значимых слов может стоять ДО скобки-синонима.
 *
 * Замер показал, что одной короткой скобки мало: она бывает и торговым именем
 * («Набор реагентов … концентрации этанола в крови (ЭТАНОЛ-ОЛЬВЕКС)»), и
 * наполнителем («Армлен ПП СК 20-4МС-875 (графит)»), и количеством («Носки …
 * (25 пар)»). Второе имя продукта стоит сразу после него, а не в хвосте
 * длинного названия — по этому они и различаются.
 */
const SYNONYM_PARENS_AFTER = 3;

/**
 * Что означает совпадение внутри скобки: "synonym", "formulation" или null.
 *
 * В названиях реестра скобка сразу после продукта — это второе его имя:
 * «Изопропилбензол (кумол)», «2-Пропанол (изопропиловый спирт, изопропанол)»,
 * «Мел химически осажденный (карбонат кальция)». Совпадение внутри такой
 * скобки — это совпадение с самим продуктом.
 *
 * Скобка с количеством — не имя, а состав: «ТОРНАДО, ВР (360 г/л глифосата
 * к-ты)», «ГЕРБИТОКС, ВРК (500 г/л МЦПА кислоты)». Это препаративная форма
 * самого вещества, и заказчик решил считать её присутствием в реестре — но
 * отдельной пометкой, потому что ОКПД2 у неё пестицидный, а не глифосатный.
 */
function matchedInParens(rawName, queryStems) {
  const text = String(rawName ?? "");
  if (!text.includes("(")) return null;

  let formulation = null;
  const parens = topLevelParens(text);
  for (const [n, m] of parens.entries()) {
    const inner = words(stemName(m.text));
    if (!inner.some((w) => queryStems.has(w))) continue;

    if (QUANTITY_RE.test(m.text)) {
      // Составом считаем только ПЕРВУЮ скобку: она стоит сразу за именем
      // продукта и говорит, из чего он сделан. Всё, что дальше, — оговорка.
      //
      // Поймано на живых данных: «Трихлорметан (хлороформ) (стабилизированный
      // 0,6-1% мас. этанола) химически чистый» подтверждал ЭТАНОЛ. Этанол там
      // стабилизатор в доле процента, а продукт — хлороформ. Препаративная
      // форма, ради которой правило заводилось, выглядит иначе: «ТОРНАДО, ВР
      // (360 г/л глифосата к-ты)» — вещество названо в первой же скобке.
      if (n === 0) formulation = "formulation";
      continue;
    }

    // Длину меряем по значимым словам: «(1,2-пропиленгликоль, пропандиол-1,2)»
    // распадается на шесть кусков, из которых четыре — обрывки цифр, и по
    // ним скобка-синоним ошибочно выглядела бы длинной.
    const meaningful = inner.filter((w) => w.length > 1);
    if (!meaningful.length || meaningful.length > SYNONYM_PARENS_WORDS) continue;

    const before = words(stemName(text.slice(0, m.at))).filter(
      (w) => w.length > 1,
    ).length;
    if (before > SYNONYM_PARENS_AFTER) continue;

    // Запрос должен покрывать ЦЕЛИКОМ хотя бы одно из перечисленных в скобке
    // названий, а не одно слово внутри длинного.
    //
    // Поймано на живых данных: «МЕКСэллара® (этилметилгидроксипиридина
    // сукцинат), раствор для внутривенного введения» подтверждал запрос
    // «Сукцинаты». Скобка там не синоним лекарства, а его действующее
    // вещество, и «сукцинат» — лишь вторая половина его названия.
    //
    // Перечисление в скобке разбираем по запятым: «(1,2-пропиленгликоль,
    // пропандиол-1,2)» — это ДВА названия одного вещества, и покрыть надо
    // любое из них, а не оба сразу.
    if (!coversWholeAlternative(m.text, queryStems)) continue;

    return "synonym";
  }
  return formulation;
}

/**
 * Покрывает ли запрос целиком хотя бы одно название из скобки.
 *
 * Скобка может перечислять несколько имён одного вещества через запятую —
 * тогда довольно любого из них. Запятая внутри числа («1,2-пропиленгликоль»)
 * разделителем не считается: иначе название распалось бы на обрывки.
 */
function coversWholeAlternative(inner, queryStems) {
  const parts = String(inner ?? "")
    .split(/[;,](?!\s*\d)/)
    .map((s) => s.trim())
    .filter(Boolean);

  for (const part of parts) {
    const stems = words(stemName(part)).filter((w) => w.length > 1);
    if (!stems.length) continue;
    if (stems.every((w) => queryStems.has(w))) return true;
  }
  return false;
}

/**
 * Содержимое скобок верхнего уровня, вместе с вложенными.
 *
 * Регулярным выражением это не берётся: скобки в реестре вкладываются —
 * «ТОРНАДО, ВР (360 г/л глифосата к-ты (изопропиламинная соль))». Выражение
 * «(без скобок внутри)» нашло бы там только «изопропиламинную соль», то есть
 * ровно не ту часть, по которой запись и опознаётся.
 */
function topLevelParens(text) {
  const out = [];
  let depth = 0;
  let start = -1;
  for (let i = 0; i < text.length; i++) {
    const ch = text[i];
    if (ch === "(") {
      if (depth === 0) start = i;
      depth += 1;
    } else if (ch === ")" && depth > 0) {
      depth -= 1;
      if (depth === 0) out.push({ at: start, text: text.slice(start + 1, i) });
    }
  }
  // Скобка открыта и не закрыта — берём хвост: обрезанные названия в реестре
  // не редкость, и терять из-за этого содержимое незачем.
  if (depth > 0 && start >= 0) out.push({ at: start, text: text.slice(start + 1) });
  return out;
}

/**
 * Оставить из найденного только самое похожее.
 *
 * Последняя ступень лестницы ищет по любому из слов, и на общем слове
 * цепляется лишнее: «Сжиженный нефтяной газ» подтягивал «Бензол нефтяной».
 * Считаем, сколько слов запроса есть в названии записи, и оставляем только
 * записи с наибольшим совпадением. Не совпало ни одного — значит, запись
 * нашлась по слову внутри сложного прилагательного, и это не наш продукт.
 *
 * Возвращает вместе с записями слова, по которым они совпали: на мягких
 * ступенях по ним решается, значит ли совпадение хоть что-нибудь.
 *
 * Считает заодно два признака — ПОКА ТОЛЬКО СЧИТАЕТ, на отбор они не влияют.
 * Нужны, чтобы померить на живом реестре дыру с однословными названиями: для
 * запроса из одного слова «совпали все слова» вырождается в «это слово где-то
 * в записи есть», и «Ноутбук» подтверждался записью про влажные салфетки,
 * годные в том числе для ноутбуков.
 *
 * 1. Доля — какую часть слов САМОЙ ЗАПИСИ объяснило совпадение. У салфеток
 *    это 5%. Но одной доли мало: «Полиэтилен» против «Полиэтилен высокого
 *    давления 15803-020» — тоже всего 20%, а совпадение верное. Марки, сорта
 *    и артикулы раздувают знаменатель у совершенно правильных записей.
 * 2. Место — на каком по счёту слове записи совпадение началось. Здесь
 *    разница видна резко: у полиэтилена это слово ПЕРВОЕ, а у салфеток
 *    «ноутбук» стоит в конце, в перечислении, для чего они годятся. Записи
 *    реестра устроены как «продукт, потом уточнения».
 *
 * Замер на 127 подтверждённых с живых графов: на первом слове 89 совпадений,
 * и все верные, кроме одного. Дальше идёт вперемешку — значит, одним местом
 * тоже не обойтись, и к нему нужны два уточнения:
 *
 * 3. Скобка. В реестре скобка после названия — это синоним: «Изопропилбензол
 *    (кумол)», «Мел химически осажденный (карбонат кальция)», «2-Пропанол
 *    (изопропиловый спирт)». Совпало внутри КОРОТКОЙ скобки — совпало с самим
 *    продуктом, где бы та скобка ни стояла. Длинная скобка — это уже состав
 *    («360 г/л глифосата к-ты»), и она так не считается.
 * 4. Два слова. Совпадение из одного слова в середине названия — почти всегда
 *    случайность: «Платина» в «Грунтовке НИПОЛ ПЛАТИНА», «МЭК» в «Ткани
 *    прорезиненной МЭК». Два и более значимых слова подряд так не совпадают.
 *
 * Порог подбирается замером, а не на глаз: прошлая попытка отсеять мусор
 * угаданным числом провалилась (см. выше про редкость слова).
 */
function keepBestOverlap(rows, rawName, required = null) {
  const queryPairs = stemPairs(rawName);
  const queryStems = new Set(queryPairs.map((p) => p.stem));
  if (!queryStems.size) return { rows, shared: [], coverage: [], dropped: [] };
  // Слово запроса так, как его написали, — для объяснений: «натрий», а не «натри».
  const asWritten = new Map(queryPairs.map((p) => [p.stem, p.word]));

  // Числа-обозначения запроса («Фторопласт-40») и спрошенный элемент
  // («Натрий») — считаются раз на запрос, сверяются с каждой записью.
  const numbers = designationNumbers(rawName);
  const element = askedElement(queryPairs);
  // Спрошенное вещество по справочнику — чтобы узнать запись про другой
  // изомер того же корня: «О-Ксилол» при запросе «Ксилол». См. otherIsomer.
  const askedCanon = identify(rawName)?.canon ?? null;
  // Слова запроса с приставкой изомера: «м-Ксилол» спрашивает изомер.
  const queryMarked = new Set();
  for (const m of String(rawName ?? "").matchAll(ISOMER_MARK)) {
    queryMarked.add(stemWord(normalizeName(m[2])));
  }

  let best = 0;
  const scored = rows.map((row) => {
    // Усечённые слова считаем из названия на месте: колонки name_stem в базе
    // нет — она нужна была только полнотекстовому индексу и место занимала
    // впустую. Строк тут не больше двух сотен, и ответ кладётся в кэш.
    // Список, а не множество: по нему видно не только ЧТО совпало, но и ГДЕ.
    const rowPairs = stemPairs(bindCompounds(row.name || "", queryStems));
    const rowList = rowPairs.map((p) => p.stem);
    const rowStems = new Set(rowList);
    // Число запроса, стоящее в записи не при своём слове, совпадением не
    // считается — см. designationNumbers.
    const detached = detachedNumbers(rowList, numbers);
    const matches = (w) => queryStems.has(w) && !detached.has(w);
    const shared = [];
    for (const s of queryStems) if (rowStems.has(s) && !detached.has(s)) shared.push(s);
    if (shared.length > best) best = shared.length;

    // Номер первого совпавшего слова — считаем настоящие слова, пропуская
    // однобуквенные. Иначе «Н-БУТАН ОЧИЩЕННЫЙ» даёт «бутану» второе место
    // из-за приставки «н», хотя название начинается именно с него.
    let at = -1;
    let long = 0;
    // Порядковый номер совпавшего слова в самом списке, без пропуска коротких:
    // по нему видно, что стояло в названии ДО вещества.
    let atRaw = -1;
    // Место каждого совпавшего слова (первое вхождение) — тем же счётом, что
    // и at. По нему видно, стоят ли совпавшие слова вместе или одно в начале,
    // а другое в хвосте, где названо уже сырьё или состав.
    const firstAt = new Map();
    for (let i = 0; i < rowList.length; i++) {
      const w = rowList[i];
      if (matches(w) && !firstAt.has(w)) {
        firstAt.set(w, long);
        if (at < 0) {
          at = long;
          atRaw = i;
        }
      }
      if (w.length > 1) long += 1;
    }
    const strongShared = shared.filter((s) => s.length > 2);
    const lastAt = strongShared.length
      ? Math.max(...strongShared.map((s) => firstAt.get(s) ?? -1))
      : -1;

    // Слово, которое требовал индекс, а сверка в записи не признала.
    // Индекс видит слова по отдельности и находит «40» где угодно, а
    // «аммиачную» — и внутри «известково-аммиачной»; отбор строже, и
    // расхождение значит, что запись не про то.
    const missing = required ? [...required].filter((w) => !shared.includes(w)) : [];
    let incomplete = null;
    if (missing.length) {
      const number = missing.find((w) => detached.has(w));
      const half = halfCompound(row.name || "", queryStems);
      incomplete = number
        ? `число «${number}» не при своём слове`
        : half
          ? `сложное слово «${half}» совпало половиной`
          : `нет слова «${asWritten.get(missing[0]) ?? missing[0]}»`;
    }

    return {
      row,
      shared,
      incomplete,
      rowWords: rowStems.size,
      at,
      lastAt,
      // Значимые совпавшие слова: «2,4 Д» цеплялась за «Пакеты д/ЗАМОРОЗКИ
      // ПНД» тремя «словами» — «2», «4» и «д». Совпадением это не назовёшь.
      strong: shared.filter((s) => s.length > 2).length,
      parens: matchedInParens(row.name || "", queryStems),
      // Слово-класс впритык к совпавшему: запись про соединение, не про него.
      foreignClass: foreignCompound(rowList, queryStems),
      // Спросили сам элемент, а в записи он только в косвенном падеже.
      elementCompound: element ? elementInCompound(rowPairs, element) : false,
      // Рядом с совпавшим — другой элемент: двойная соль или смесь.
      otherElement: otherElement(rowPairs, matches),
      // Совпали ОДНИ слова, не называющие вещество, — названия классов
      // соединений или формы поставки. Значит, спросили про класс, а не про
      // вещество, и подтверждать таким совпадением нечего.
      onlyClass:
        shared.length > 0 &&
        shared.every((w) => COMPOUND_CLASS.has(w) || FORM_WORDS.has(w)),
      // Перед веществом стоит слово, называющее не его: набор, мерный реактив
      // или продукт, который на вещество ДЕЙСТВУЕТ.
      //
      // Смотрим всё, что в названии стоит ДО совпавшего слова, а не только
      // первое слово. «Восстановитель оксидов азота AUS 32» первым словом
      // ловился, а «Мочевина восстановитель оксидов азота AUS 35» — уже нет,
      // хотя это тот же AdBlue. Что стоит ПОСЛЕ вещества, запись не меняет:
      // «Янтарная кислота, стандарт-титр» — про янтарную кислоту.
      supplyForm:
        atRaw > 0 &&
        rowList
          .slice(0, atRaw)
          .some((w) => SUPPLY_FORM.has(w) && !queryStems.has(w)),
      // Перед веществом — продукт, который его содержит. См. PRODUCT_BEFORE.
      productBefore:
        (atRaw > 0 &&
          rowList
            .slice(0, atRaw)
            .some((w) => PRODUCT_BEFORE.has(w) && !queryStems.has(w))) ||
        basedOnSubstance(row.name || "", queryStems),
      madeOf: madeOfSubstance(row.name || "", queryStems),
      // Лекарство или медизделие — свидетельство второго сорта, см. lookupProduct.
      medicine: isMedicine(rowList),
      // Мочевинный раствор для дизелей — тоже второго сорта, как препарат.
      ureaSolution: isUreaSolution(rowList),
      // Препаративная форма пестицида: «Сера 400, КС (фунгицид)».
      pesticideForm: isPesticideForm(row.name || ""),
      // Изомер, который справочник знает отдельным веществом.
      otherIsomer: otherIsomer(row.name || "", queryStems, askedCanon, queryMarked),
    };
  });

  // Отсеянные сравнением — для разбора (см. explainRows).
  const droppedOf = (list) =>
    list.map((s) => ({
      row: s.row,
      why:
        s.incomplete ??
        (s.shared.length ? "совпало меньше слов, чем у лучших записей" : "не совпало ни одно слово"),
    }));
  if (!best) return { rows: [], shared: [], coverage: [], dropped: droppedOf(scored) };
  const kept = scored.filter((s) => s.shared.length === best);
  return {
    dropped: droppedOf(scored.filter((s) => s.shared.length !== best)),
    rows: kept.map((s) => s.row),
    // Слова, по которым совпало: объединение по оставшимся записям.
    shared: [...new Set(kept.flatMap((s) => s.shared))],
    coverage: kept.map((s) => ({
      name: s.row.name ?? null,
      incomplete: s.incomplete,
      rowWords: s.rowWords,
      share: s.rowWords ? s.shared.length / s.rowWords : 0,
      at: s.at,
      lastAt: s.lastAt,
      strong: s.strong,
      parens: s.parens,
      foreignClass: s.foreignClass,
      elementCompound: s.elementCompound,
      otherElement: s.otherElement,
      onlyClass: s.onlyClass,
      supplyForm: s.supplyForm,
      productBefore: s.productBefore,
      madeOf: s.madeOf,
      medicine: s.medicine,
      ureaSolution: s.ureaSolution,
      pesticideForm: s.pesticideForm,
      otherIsomer: s.otherIsomer,
    })),
  };
}

/**
 * «Из» прямо перед веществом: запись про изделие ИЗ него, а не про него самого.
 *
 * «Стержни из фторопласта-4 общего назначения», «Диск из фторопласта-4
 * прессованный», «Листы из полиэтилена низкого давления» — снимок нашёл их у
 * политетрафторэтилена и полиэтилена, как только поиск стал спрашивать все
 * написания.
 */
function madeOfSubstance(rawName, queryStems) {
  const before = tokensBefore(rawName, queryStems);
  return before[before.length - 1] === "из";
}

/**
 * «На основе» прямо перед веществом: товар, сделанный на веществе, а не оно
 * само, — «Добавка на основе пероксида водорода Booster». Снимок нашёл её у
 * перекиси по правилу «два слова рядом». Считается тем же запретом, что
 * PRODUCT_BEFORE, и так же уступает препаративной форме.
 */
function basedOnSubstance(rawName, queryStems) {
  const before = tokensBefore(rawName, queryStems);
  return before[before.length - 2] === "на" && before[before.length - 1] === "основе";
}

/**
 * Слова названия, стоящие ДО вещества, — как есть, с предлогами: words()
 * предлоги выбрасывает, а здесь они и нужны. «Из» и «на основе» говорят, что
 * вещество — материал или основа другого товара.
 */
function tokensBefore(rawName, queryStems) {
  const tokens = normalizeName(bindCompounds(rawName, queryStems)).split(" ").filter(Boolean);
  const first = tokens.findIndex((t) => queryStems.has(stemWord(t)));
  return first > 0 ? tokens.slice(0, first) : [];
}

/**
 * Числа, приписанные в запросе к слову через дефис: «Фторопласт-40»,
 * «Пропанол-2», «1,4-Бутандиол».
 *
 * Такое число — часть имени: марка или место заместителя. В записи оно
 * совпадает, только если стоит рядом с тем же словом — до него или после,
 * одно или списком: «Пропанол-2» и «2-Пропанол», «Бутандиол-1,4» и
 * «1,4-Бутандиол» — одно и то же. Иначе «Фторопласт-40» (сополимер с
 * этиленом) подтверждался записью «фторопласт-ТМ моделей ПН25, ПН 40,
 * Ф-4ТМ» — это политетрафторэтилен, а «40» там номер модели через три слова
 * от «фторопласта».
 *
 * Сперва правило признавало число только ПОСЛЕ слова, и снимок это поймал:
 * «Изопропанол» (он же «Пропанол-2») потерял «2-Пропанол химически чистый».
 *
 * Число через пробел — «Соляная кислота 36%» — не часть имени, а
 * концентрация, и так не проверяется: в записи оно может стоять где угодно.
 *
 * Число → основы слов, к которым оно приписано.
 */
function designationNumbers(rawSpelling) {
  const text = String(rawSpelling ?? "").toLowerCase().replace(/ё/g, "е");
  const out = new Map();
  const add = (numbers, word) => {
    const stem = stemWord(normalizeName(word));
    for (const n of numbers.split(/[.,]\s*/).filter(Boolean)) {
      if (!out.has(n)) out.set(n, new Set());
      out.get(n).add(stem);
    }
  };
  // Слово-число: «фторопласт-40», «бутандиол-1,4». Число, за которым сразу
  // идут буквы («фторопласт-4мб»), — уже другое обозначение, целым словом.
  for (const m of text.matchAll(/([а-яa-z]{2,})\s*-\s*(\d+(?:[.,]\s*\d+)*)(?![\dа-яa-z])/g)) {
    add(m[2], m[1]);
  }
  // Число-слово: «2-пропанол», «1,4-бутандиол». Число внутри обозначения
  // («с4-фракция») не в счёт — оно приклеено к букве.
  for (const m of text.matchAll(/(?<![\d.,а-яa-z])(\d+(?:[.,]\s*\d+)*)\s*-\s*([а-яa-z]{2,})/g)) {
    add(m[1], m[2]);
  }
  return out;
}

/**
 * Числа из designationNumbers, которые в записи стоят не при своём слове.
 *
 * «При своём» — вплотную до или после слова, одно или в списке чисел, либо
 * за первой буквой слова: «Фторопласт Ф-40 марки П» — то же обозначение,
 * записанное сокращённо.
 */
function detachedNumbers(rowList, numbers) {
  const detached = new Set();
  const isNumber = (w) => /^\d+$/.test(w);
  for (const [number, words] of numbers) {
    const initials = new Set([...words].map((w) => w[0]));
    let seen = false;
    let attached = false;
    for (let j = 0; j < rowList.length; j++) {
      if (rowList[j] !== number) continue;
      seen = true;
      // Весь список чисел, в котором стоит это: «1 4» в «1,4-бутандиол».
      let from = j;
      let to = j;
      while (from > 0 && isNumber(rowList[from - 1])) from -= 1;
      while (to + 1 < rowList.length && isNumber(rowList[to + 1])) to += 1;
      const before = rowList[from - 1];
      const after = rowList[to + 1];
      if (
        (before && (words.has(before) || (before.length === 1 && initials.has(before)))) ||
        (after && words.has(after))
      ) {
        attached = true;
      }
    }
    if (seen && !attached) detached.add(number);
  }
  return detached;
}

/**
 * Основы названий элементов — для правила «рядом другой элемент».
 *
 * Элементы на «-ий» и ходовые металлы, во всех падежах сразу: основа у них
 * общая (см. ELEMENT_NOUNS в normalize.js).
 */
const ELEMENT_STEMS = new Set(
  [
    ...ELEMENT_NOUNS,
    "медь", "меди", "цинк", "железо", "железа", "никель", "кобальт", "хром",
    "марганец", "свинец", "олово",
  ].map(stemWord),
);

/**
 * Рядом с совпавшим словом — другой элемент, которого в запросе нет:
 * «Аммоний кальций нитрат» при запросе «Нитрат аммония», «Калий кальций
 * нитрат» при запросе «Нитрат кальция», «Доломит (карбонат кальция и
 * магния)» при запросе «Карбонат кальция». Это двойная соль или смесь, то
 * есть другое вещество.
 *
 * Поймано снимком сразу после того, как «аммоний» и «аммония» получили общую
 * основу: до того «Аммоний кальций нитрат» не совпадал с «Нитратом аммония»
 * по случайности — падежи расходились. Возвращает само слово, для отказа.
 */
function otherElement(rowPairs, matches) {
  for (let i = 0; i < rowPairs.length; i++) {
    const { stem } = rowPairs[i];
    if (!matches(stem)) continue;
    // Соседство частей ХИМИЧЕСКОГО названия — элемента или класса («нитрат»,
    // «карбонат»). Не любого слова: в «Полевой шпат (калий натрий
    // алюмосиликат)» калий описывает состав шпата, а не другое вещество.
    if (!ELEMENT_STEMS.has(stem) && !COMPOUND_CLASS.has(stem)) continue;
    for (const j of [i - 1, i + 1]) {
      const near = rowPairs[j];
      if (near && ELEMENT_STEMS.has(near.stem) && !matches(near.stem)) return near.word;
    }
  }
  return null;
}

/**
 * Спрошен сам элемент — «Натрий», «Магний»: все значимые слова запроса —
 * элементы в именительном падеже. Возвращает их основы, иначе null.
 */
function askedElement(queryPairs) {
  const strong = queryPairs.filter((p) => p.stem.length > 2);
  if (!strong.length || !strong.every((p) => ELEMENT_NOUNS.has(p.word))) return null;
  return new Set(strong.map((p) => p.stem));
}

/**
 * Элемент назван в записи только в косвенном падеже: «Натрия гипохлорит»,
 * «Магния стеарат», «Кали едкое».
 *
 * Пока «натрий» и «натрия» усекались по-разному, такая запись с запросом
 * «Натрий» не совпадала вовсе — по случайности, но верно: элемент в
 * родительном падеже стоит в имени соединения. Теперь основа у падежей общая,
 * и различие держится здесь, явно. Сам элемент реестр называет в именительном:
 * «Натрий металлический», «Магний первичный».
 */
function elementInCompound(rowPairs, elementStems) {
  const hits = rowPairs.filter((p) => elementStems.has(p.stem));
  return hits.length > 0 && !hits.some((p) => ELEMENT_NOUNS.has(p.word));
}

/**
 * Прошла бы эта запись вето, спроси мы продукт ровно этим написанием.
 *
 * Нужна отчётам о написаниях-ловушках. Поиском этого не узнать: lookupProduct
 * ищет сразу по всем написаниям записи справочника, и по какому именно
 * совпало — в ответе не видно.
 *
 * Оценка СВЕРХУ: в настоящем поиске запись ещё соревнуется с остальными
 * найденными за число общих слов и может отсеяться там. Отчёту так и надо —
 * пусть лучше покажет лишнее, чем пропустит протечку.
 */
function passesVeto(rowName, spelling) {
  const { coverage } = keepBestOverlap([{ name: rowName }], spelling);
  return confirms(coverage[0]);
}

/**
 * Называет ли сам классификатор наше вещество под этим кодом.
 *
 * Сравниваем название позиции ОКПД2 с известными написаниями продукта:
 * покрыто целиком хотя бы одно — значит, классификатор говорит ровно про то,
 * что мы спросили. «Гидрокарбонат натрия» известен и как «бикарбонат натрия»,
 * а позиция 20.13.43.191 называется «Водородкарбонат натрия (бикарбонат
 * натрия)» — совпало, и код про наше вещество.
 *
 * Берём ТОЛЬКО точное название позиции. Название ГРУППЫ над кодом слишком
 * широко: «Спирты одноатомные насыщенные» подошло бы дюжине разных веществ, и
 * повышать по нему код значило бы верить общему больше, чем частному.
 *
 * Слова короче трёх букв отбрасываем: по ним совпадает что угодно.
 */
function codeNamesSubstance(code, spellings) {
  if (!okpd2NameExact(code)) return false;
  const codeStems = new Set(words(stemName(okpd2Name(code) ?? "")));
  if (!codeStems.size) return false;

  for (const spelling of spellings) {
    const stems = words(stemName(spelling)).filter((w) => w.length > 2);
    if (!stems.length) continue;
    if (stems.every((w) => codeStems.has(w))) return true;
  }
  return false;
}

/**
 * Позиция классификатора названа ровно веществом, без уточнений: «Бутан», а
 * не «Бутан сжиженный». Нужна только ничьей в выборе кода.
 */
function codeIsSubstance(code, spellings) {
  if (!okpd2NameExact(code)) return false;
  const key = (text) =>
    [...new Set(words(stemName(text)).filter((w) => w.length > 2))].sort().join(" ");
  const codeKey = key(okpd2Name(code) ?? "");
  return Boolean(codeKey) && spellings.some((s) => key(s) === codeKey);
}

/**
 * Уточнить код реестра по классификатору: позиция под ним, названная ровно
 * нашим веществом, или null.
 *
 * Заявители часто ставят код категории, а не своей позиции. У «Капролактама»
 * записи стоят под 20.14.52.110 «Соединения гетероциклические, не включенные
 * в другие группировки», а под ней в классификаторе есть 20.14.52.111
 * «Капролактам» — по ссылке из карточки человек видел общую категорию и
 * уточнение строчкой ниже.
 *
 * Берём только позицию, названную РОВНО веществом, и только если она одна.
 * «Бензол» под 20.14.12.130 «Бензолы» уточнять нечем: под ней каменноугольный,
 * сланцевый и нефтяной, и выбирать за человека нельзя. Совпадение по части
 * слов не годится вовсе: «Азот» нашёл бы «Закись азота» — родительный падеж
 * усекается в ту же основу.
 */
function refineOkpd2(code, spellings) {
  if (!code || !spellings.length || codeIsSubstance(code, spellings)) return null;
  const hits = okpd2Below(code).filter((c) => codeIsSubstance(c.code, spellings));
  return hits.length === 1 ? hits[0].code : null;
}

/**
 * Свернуть строки реестра в сводку по продукту.
 *
 * spellings — известные написания продукта; по ним решается, какой из кодов
 * ОКПД2 говорит про него, а какой про что-то своё.
 */
function summarize(rows, spellings = []) {
  const byProducer = new Map();
  const regions = new Set();
  let anyActive = false;
  // Код ОКПД2 у каждой записи свой, и брать первый попавшийся нельзя: на
  // «Водороде» так выходило 20.13.63.000 «Пероксид водорода» — чужое вещество,
  // и вдобавок код, исключённый из классификатора. Считаем, какой код у
  // записей встречается чаще, и говорим, сколько их всего: если кодов много,
  // это само по себе признак, что записи собрались разные.
  const okpd2Counts = new Map();
  // ТН ВЭД считаем так же: он тоже свой у каждой записи.
  const tnvedCounts = new Map();

  for (const row of rows) {
    if (row.status === "active") anyActive = true;
    if (row.okpd2) okpd2Counts.set(row.okpd2, (okpd2Counts.get(row.okpd2) ?? 0) + 1);
    if (row.tnved) tnvedCounts.set(row.tnved, (tnvedCounts.get(row.tnved) ?? 0) + 1);
    // Считаем по тому же региону, что показываем: в выгрузке адреса нет, и
    // регион выводится из ИНН — иначе счётчик регионов всегда был бы нулём.
    const region = row.region || regionByInn(row.inn);
    if (region) regions.add(region);

    // Один производитель может стоять в нескольких записях реестра: считаем его
    // один раз, но показываем действующую запись, а не первую попавшуюся.
    const key = row.inn || row.producer;
    const prev = byProducer.get(key);
    if (!prev || (prev.status !== "active" && row.status === "active")) {
      byProducer.set(key, toEntry(row));
    }
  }

  const producers = [...byProducer.values()].sort((a, b) => {
    if (a.status !== b.status) return a.status === "active" ? -1 : 1;
    return String(a.producer).localeCompare(String(b.producer), "ru");
  });

  // При равенстве берём меньший код: лишь бы ответ не плавал от порядка строк.
  const byCount = (m) =>
    [...m].sort((a, b) => b[1] - a[1] || String(a[0]).localeCompare(String(b[0])));

  // ОКПД2 выбираем не одним большинством. «Гидрокарбонат натрия» у семи
  // записей стоял под двумя кодами: 20.13.43.191 «Водородкарбонат натрия
  // (бикарбонат натрия)» у трёх и 10.89.19.150 «Добавки пищевые комплексные»
  // у четырёх. Большинство давало «пищевую добавку» — формально правду, а по
  // сути потерю: первый код называет само вещество, второй — назначение
  // товара. Поэтому сперва смотрим, какие коды классификатор связывает с этим
  // веществом, и большинство считаем уже среди них.
  //
  // Ничью решает позиция, названная РОВНО веществом. У «Бутана» две записи:
  // одна под 20.14.11.112 «Бутан», другая под 19.20.31.120 «Бутан
  // сжиженный»; при равенстве брался меньший код, и вещество получало
  // топливную позицию вместо своей.
  //
  // Порядок полный: говорит ли код о веществе, сколько у него записей, назван
  // ли он ровно веществом, и последним — сам код, чтобы ответ не плавал.
  const ranked = [...okpd2Counts].sort((a, b) => {
    const an = codeNamesSubstance(a[0], spellings);
    const bn = codeNamesSubstance(b[0], spellings);
    if (an !== bn) return an ? -1 : 1;
    if (a[1] !== b[1]) return b[1] - a[1];
    const ae = codeIsSubstance(a[0], spellings);
    const be = codeIsSubstance(b[0], spellings);
    if (ae !== be) return ae ? -1 : 1;
    return String(a[0]).localeCompare(String(b[0]));
  });
  const registryOkpd2 = ranked[0]?.[0] ?? null;
  const refined = refineOkpd2(registryOkpd2, spellings);
  const okpd2 = refined ?? registryOkpd2;
  const rankedTnved = byCount(tnvedCounts);
  const tnved = rankedTnved[0]?.[0] ?? null;

  return {
    entryCount: rows.length,
    producerCount: producers.length,
    regionCount: regions.size,
    status: anyActive ? "active" : "archived",
    okpd2,
    okpd2Name: okpd2Name(okpd2),
    /** Название самой позиции, а не группы над ней. */
    okpd2NameExact: okpd2NameExact(okpd2),
    okpd2Retired: okpd2Retired(okpd2),
    /**
     * Код записей реестра, когда классификатор уточнил его до позиции
     * вещества (okpd2 — уже уточнённый). null — код взят из реестра как есть.
     */
    okpd2Registry: refined ? registryOkpd2 : null,
    /** У скольких записей из найденных код реестра (okpd2Registry или okpd2). */
    okpd2Share: ranked[0]?.[1] ?? 0,
    /** Сколько ещё разных кодов у остальных записей. */
    okpd2Others: Math.max(0, ranked.length - 1),
    tnved,
    tnvedName: tnvedName(tnved)?.name ?? null,
    tnvedOthers: Math.max(0, rankedTnved.length - 1),
    producers,
  };
}

