const cache = new Map();
const CACHE_LIMIT = 5000;

/**
 * Счётчики базы для status(): записи, продукты, производители.
 *
 * Считаются полным проходом по базе: на миллионе записей это секунда, а
 * status() зовётся на каждый поиск. Пока сервер работает, база под ним не
 * меняется — новая от импорта встаёт на место файла, но открытое соединение
 * держит прежнюю до перезапуска. Поэтому считаем раз на соединение.
 */
let counts = null;

/**
 * Открыть базу, если она есть. Возвращает null, когда файла нет, — это штатная
 * ситуация: слой промышленных данных просто не работает.
 */
function getDb() {
  const file = dbPath();

  if (db && openedPath === file) return db;
  if (db) {
    db.close();
    db = null;
    openedPath = null;
    cache.clear();
    // Частоты слов считаны по старой базе — к новой они отношения не имеют.
    dfCache.clear();
    counts = null;
  }

  openError = null;
  if (!fs.existsSync(file)) return null;

  // Требуем модуль лениво: без него сервер обязан подниматься как прежде.
  const Database = require("better-sqlite3");
  try {
    const conn = new Database(file, { readonly: true, fileMustExist: true });
    // Открыть мало: недописанная база от прерванного импорта открывается, а
    // падает уже на первом запросе — рядом с ней лежит журнал, и SQLite хочет
    // его откатить, чего в режиме чтения сделать не может. Поэтому пробуем
    // прямо здесь, пока ошибку ещё есть куда деть.
    conn.prepare("SELECT COUNT(*) FROM sqlite_master").get();
    db = conn;
    openedPath = file;
    return db;
  } catch (e) {
    // Файл есть, а открыть нельзя: чаще всего это недописанная база от
    // прерванного импорта. Слой промышленных данных должен в таком случае
    // просто не работать — а не ронять каждый запрос к продуктам.
    db = null;
    openedPath = null;
    openError = e.message;
    return null;
  }
}

/** Сведения о подключённой базе — для интерфейса и диагностики. */
function status() {
  const conn = getDb();
  if (!conn) {
    return {
      ready: false,
      path: dbPath(),
      reason: openError
        ? `Файл базы ГИСП не читается: ${openError}. Похоже на недописанную базу — повторите импорт.`
        : "Файл базы ГИСП не найден",
    };
  }

  try {
    const meta = Object.fromEntries(
      conn
        .prepare("SELECT key, value FROM meta")
        .all()
        .map((r) => [r.key, r.value]),
    );
    counts ??= conn
      .prepare(
        `SELECT COUNT(*) AS entries,
                COUNT(DISTINCT name_norm) AS products,
                COUNT(DISTINCT inn) AS producers
         FROM products`,
      )
      .get();

    return {
      ready: true,
      path: dbPath(),
      entries: counts.entries,
      products: counts.products,
      producers: counts.producers,
      /** Дата, на которую актуальна выгрузка (из meta при импорте). */
      actualAt: meta.actual_at || null,
      importedAt: meta.imported_at || null,
      source: meta.source || null,
    };
  } catch (e) {
    return { ready: false, path: dbPath(), reason: e.message };
  }
}

/** Строка реестра → вид, в котором её ждёт интерфейс. */
function toEntry(row) {
  return {
    // Показываем сокращённое название, полное отдаём рядом: в таблице
    // «ОБЩЕСТВО С ОГРАНИЧЕННОЙ ОТВЕТСТВЕННОСТЬЮ "ТЕХНОКЕРАМИКА"» занимает три
    // строки, но в подсказке оно нужно как есть — это официальное имя.
    producer: shortenCompany(row.producer),
    producerFull: row.producer,
    inn: row.inn || null,
    // Регион берём из выгрузки, а если там пусто — выводим из ИНН. В реестре
    // ПП №719 адрес не заполнен ни у одной записи, так что на деле работает
    // второй путь; признак regionFromInn говорит интерфейсу, что это место
    // учёта организации, а не обязательно место производства.
    region: row.region || regionByInn(row.inn),
    regionFromInn: !row.region && Boolean(regionByInn(row.inn)),
    product: row.name,
    // Код и его расшифровка рядом: «20.16.10.110» сам по себе ничего не
    // говорит, а название классификатора объясняет, к чему запись отнесена.
    okpd2: row.okpd2 || null,
    okpd2Name: okpd2Name(row.okpd2),
    // Код мог быть снят с классификатора уже после регистрации записи.
    okpd2Retired: okpd2Retired(row.okpd2),
    tnved: row.tnved || null,
    tnvedName: tnvedName(row.tnved)?.name ?? null,
    status: row.status,
    statusLabel: row.status_raw || (row.status === "active" ? "Действует" : "В архиве"),
    regNumber: row.reg_number || null,
    regDate: row.reg_date || null,
    // Дата, когда запись перестала действовать. В выгрузке ПП №719 колонки со
    // статусом нет, и признак «в архиве» выводится как раз отсюда — значит,
    // стоит показать и саму дату, а не только ярлык.
    endedAt: row.ended_at || null,
    url: row.url || null,
  };
}

/**
 * Имена, которые интерфейс даёт узлу при создании, пока человек не вписал своё.
 *
 * Список закрытый и короткий: это ровно те подписи, что ставит клиент (см.
 * addNode в gptSlice). Держим его здесь, а не на клиенте, потому что врать о
 * реестре нельзя никакому клиенту — в том числе открытому по ссылке графу и
 * сохранённому полгода назад.
 */
const PLACEHOLDER_NAMES = new Set(
  [
    "Новый продукт",
    "Новое преобразование",
    "Новый узел",
    "Без названия",
    // Слово, называющее ВИД узла, а не вещество: узел подписали «Продукт» и
    // на том остановились. Веществом такое имя не бывает, а в реестре полно
    // записей со словом «продукт» в названии — сегодня ни одна не проходит
    // вето, но держаться на этом везении не стоит.
    "Продукт",
    "Преобразование",
    "Узел",
  ].map((s) => normalizeName(s)),
);

/**
 * Подпись, которая не называет вещество: заготовка интерфейса или одни
 * определения.
 *
 * Отдельной функцией, потому что спрашивает не только поиск. Отчёт по графам
 * тоже обязан знать: узел с подписью «Новый продукт» — не кандидат в
 * справочник, а неназванный узел, и предлагать вписать его в словарь
 * бессмысленно. Порознь эти двое уже разошлись бы: сервер отказывался
 * отвечать, а отчёт звал дописывать.
 */
function isPlaceholderName(rawName) {
  const normalized = normalizeName(rawName);
  if (!normalized) return false;
  return PLACEHOLDER_NAMES.has(normalized) || isQualifierOnly(rawName);
}

/**
 * Найти продукт в реестре.
 *
 * Сначала пробуем точное совпадение нормализованных названий, затем спускаемся
 * по лестнице всё более мягких полнотекстовых запросов и останавливаемся на
 * первой ступени, что-то нашедшей. Уровень совпадения возвращаем вместе с
 * данными: «нашлось по одному слову» и «нашлось целиком» — разные вещи, и в
 * интерфейсе их стоит различать.
 *
 * Ищем не только по спрошенному названию, но и по всем известным написаниям
 * вещества: реестр заполняют люди, и запись стоит под тем названием, какое было
 * у заявителя. По «ПЭНД» не находится ничего, по «полиэтилену низкого давления»
 * — находится, а вещество одно.
 */
function lookupProduct(rawName, opts) {
  const conn = getDb();
  const empty = {
    found: false,
    match: null,
    entryCount: 0,
    producerCount: 0,
    regionCount: 0,
    status: null,
    okpd2: null,
    producers: [],
  };

  if (!conn) return empty;

  const normalized = normalizeName(rawName);
  if (!normalized) return empty;

  // Подпись, которая не называет вещество, реестру не задаётся вовсе.
  //
  // Два вида, и оба пришли с живых графов:
  //
  //   «Новый продукт» — заготовка, которую интерфейс ставит узлу при
  //     создании. Ступень «значимые слова» сводит её к одному «новому»:
  //     «продукт» выброшен из ядра как общее.
  //   «Новый» — одни определения без существительного. Тут и сводить нечего.
  //
  // В обоих случаях в реестре находится торговое имя вроде «Жироудалитель
  // „Новый Элемент“»: слово совпадает вторым, покрывает треть записи, и отбор
  // такое подтверждает. Правило отбора верное — спросили не о том, и узел
  // получал чужого производителя, чужой ОКПД2 и ярлык «Найден в реестре».
  //
  // Почему не проще. Отправить «новый» в GENERIC_WORDS нельзя: там он
  // противопоставлен «вторичному», и первичный полиэтилен слился бы со
  // вторичным сырьём. Вырезать слово из названия тоже нельзя: «Новый
  // продукт» — заготовка, а «Полиэтилен новый» — возможное название.
  // Поэтому заготовки сверяются ЦЕЛИКОМ, а определения — правилом о том,
  // чем слово приходится названию.
  if (isPlaceholderName(rawName)) {
    return { ...empty, placeholder: true };
  }

  // Разбор мимо кэша: кэш хранит обычный ответ, и вернуть его вместо разбора
  // значило бы промолчать там, где как раз и спросили «почему».
  const cached = opts?.explain ? null : cache.get(normalized);
  if (cached) return cached;

  const spellings = spellingsOf(rawName);
  const known = identify(rawName);

  /**
   * Категория классификатора по названию — на случай, когда реестр промолчит.
   *
   * Классификатор и реестр — разные вещи, а в карточке это сливалось в одно
   * «записи нет». Бензол в ОКПД2 есть (20.14.12.130 «Бензолы»), а в реестре
   * ПП №719 его нет: код категории существует всегда, запись появляется лишь
   * когда завод заявил продукцию. Без этой строки карточка выглядела так,
   * будто мы просто не нашли — и ей переставали верить.
   */
  const category = okpd2ByName(spellings)[0] ?? null;
  /**
   * Код ТН ВЭД по названию — тоже классификатор, а не реестр: у записей ГИСП
   * код бывает не всегда, а у ненайденного продукта его нет вовсе. Карточка
   * показывает его, когда кода из реестра нет, с пометкой «по
   * классификатору». Идентификатором не служит (tnvedByName.js).
   */
  const tnvedCategory = tnvedByName(rawName);

  // Вещество справочника — только среди веществ и материалов
  // (SUBSTANCE_CLASSES): не «Генератор азота» для азота.
  const exactStmt = conn.prepare(
    `SELECT * FROM products WHERE name_norm = ?
     ${known ? `AND ${substanceClassSql()}` : ""}
     LIMIT ${MAX_ENTRIES_PER_PRODUCT}`,
  );
  const ftsStmt = conn.prepare(
    `SELECT p.* FROM products_fts f
     JOIN products p ON p.id = f.rowid
     WHERE products_fts MATCH ?
     ${known ? `AND ${substanceClassSql("p.")}` : ""}
     ORDER BY rank
     LIMIT ${MAX_ENTRIES_PER_PRODUCT}`,
  );

  // Лестницу проходим по написаниям целиком: сперва все точные, потом все
  // мягкие. Иначе «похоже» по первому написанию побеждало бы «точно» по
  // второму.
  const ladders = spellings.map((spelling) => ({
    spelling,
    own: normalizeName(spelling) === normalized,
    steps: buildQueryLadder(spelling),
  }));

  // Обход идёт ПО СТУПЕНЯМ, а написания перебираются внутри. Наоборот было
  // нельзя, и это ровно та ошибка, от которой оговорка выше уберегает точное
  // совпадение, а лестницу не уберегала: первое написание успевало спуститься
  // до мягкой ступени раньше, чем второе пробовало строгую.
  //
  // Поймано на «Пищевой соде». Её собственное написание цеплялось мягкой
  // ступенью за три записи со словом «пищевой», цикл на этом обрывался — и
  // «Гидрокарбонат натрия», который нашёл бы все семь записей строгой
  // ступенью, не пробовался вовсе. Мягкие три потом отбрасывал отбор, и
  // вещество выходило ненайденным, хотя в реестре оно есть.
  // Ступень, не перечисленная в LADDER_ORDER, идёт в конец, а не мимо.
  const levels = [...LADDER_ORDER];
  for (const l of ladders) {
    for (const s of l.steps) if (!levels.includes(s.level)) levels.push(s.level);
  }

  /** Попытки поиска — в том порядке, в каком их надо пробовать. */
  function* attempts() {
    // Точное совпадение по любому из написаний — самое надёжное, что есть.
    for (const spelling of spellings) {
      yield {
        level: "exact",
        spelling,
        run: () => exactStmt.all(normalizeName(spelling)),
      };
    }
    for (const level of levels) {
      for (const { spelling, own, steps } of ladders) {
        // Мягкие ступени ищут по любому из слов, и на синонимах это даёт
        // ложные попадания: «Незамерзайка» через «стеклоомывающую жидкость»
        // цеплялась за «Жидкость тормозная» по общему слову. Нечёткость
        // допустима один раз, а не дважды подряд — по чужим написаниям идём
        // только строгими ступенями.
        if (!own && !STRICT_LEVELS.has(level)) continue;
        const step = steps.find((s) => s.level === level);
        if (!step) continue;
        // «Значимые слова» считаются строгими, только пока не выбросили
        // различие. Выбросив короткое слово, ступень перестаёт отличать
        // вещество от соседнего: «П-Ксилол» сводится к «ксилолу» — то есть к
        // орто- и мета- заодно, — а «(NH4)S» к «nh4», то есть к любому
        // аммонию. Оба случая пришли с живых данных: «Пара-ксилол»
        // подтверждался орто-ксилолом, «Сульфид аммония» — сульфатом.
        //
        // По СВОЕМУ написанию такая ступень работает как прежде: там
        // нечёткость всего одна, и её видно в ответе уровнем совпадения.
        if (!own && step.lossy) continue;
        yield {
          level,
          spelling,
          required: requiredStems(spelling, level),
          run: () => ftsStmt.all(step.query),
        };
      }
    }
  }

  // Ответ — первая попытка, давшая ПОДТВЕРЖДЁННЫЕ записи на строгой ступени.
  //
  // Раньше ответом была первая попытка, давшая хоть что-то, и отбор уже потом
  // мог выбросить всё найденное — тогда вещество выходило ненайденным, хотя
  // следующее написание нашло бы его. Поймано на КАС: «Карбамидно-аммиачная
  // смесь» цеплялась за две записи «Удобрения жидкие минеральные: карбамидно-
  // аммиачная смесь (КАС-32)», отбор их отклонял (вещество стоит четвёртым
  // словом), и до «КАС» с пятью записями «Удобрение карбамидоаммиачное (КАС)»
  // очередь не доходила.
  //
  // Если подтверждённых нет нигде, ответ прежний: первое, что нашлось, с
  // разбором того, почему отклонено.
  //
  // И собираем записи по ВСЕМ написаниям, а не по первому сработавшему. Иначе
  // ответ был записями одной попытки: «Дихлорметан» находил свою запись и до
  // «Метилен хлористый технический» не доходил, «Карбамидоформальдегидный
  // концентрат» находил одну запись с точно таким названием и не видел пяти
  // «Концентрат карбамидоформальдегидный (КФК-85)». Справочник обещал «поиск
  // по всем написаниям сразу» — теперь это правда.
  //
  // Собираем в пределах УРОВНЯ: «точно» и «все слова» — один уровень (точно
  // названная запись и так содержит все слова), «значимые слова» — следующий,
  // и к нему спускаемся, только если на первом не подтвердилось ничего. Каждое
  // написание проверяется отбором по себе самому: «ПЭНД» — по «ПЭНД».
  const tierOf = (level) => (level === "exact" ? "all-words" : level);
  let first = null;
  let tier = null;
  /** Подтвердившиеся попытки уровня — из них и собирается ответ. */
  const gathered = [];
  /** Строгие попытки, где отбор не подтвердил ничего, — только для разбора. */
  const refused = [];
  /** Записи, которые отбор отсеял раньше вето, — тоже только для разбора. */
  const dropped = [];
  for (const attempt of attempts()) {
    // Уровень кончился, а подтверждённое уже есть — ниже не спускаемся:
    // нижний уровень мягче, и его записи хуже собранных.
    if (tier && tierOf(attempt.level) !== tier) break;
    let found;
    try {
      found = attempt.run();
    } catch {
      // Кривой запрос к индексу — просто пробуем следующую ступень.
      continue;
    }
    if (!found.length) continue;
    const hit = {
      rows: found,
      match: attempt.level,
      matchedAs: attempt.spelling,
      required: attempt.required,
    };
    if (!first) first = hit;
    // Мягкая ступень «найдено» не даёт (см. ниже), а строгие к этому месту
    // перебраны все — дальше искать нечего.
    if (LOOSE_LEVELS.has(attempt.level)) break;
    const trial = keepBestOverlap(found, attempt.spelling, attempt.required);
    if (opts?.explain) dropped.push(...trial.dropped);
    if (trial.rows.some((row, i) => confirms(trial.coverage?.[i]))) {
      tier = tierOf(attempt.level);
      gathered.push({ hit, trial });
    } else if (opts?.explain) {
      refused.push(trial);
    }
  }

  const hit = gathered[0]?.hit ?? first;
  const rows = hit?.rows ?? [];
  const match = hit?.match ?? null;
  // Написание, которым нашли: по нему же считается отбор. Искали «ПЭНД», нашли
  // по «полиэтилену низкого давления» — сверять найденное надо со вторым,
  // иначе совпадений слов не будет ни одного и отбор выбросит всё.
  const matchedAs = hit?.matchedAs ?? rawName;

  // Отбор может отклонить всё найденное: полнотекстовый индекс ищет по словам
  // и не знает, что слово было частью сложного прилагательного.
  const picked = gathered.length
    ? combineTrials(gathered.map((g) => g.trial))
    : rows.length
      ? keepBestOverlap(rows, matchedAs, hit?.required ?? null)
      : { rows: [], shared: [], coverage: [] };

  const kept = picked.rows;

  // Совпадение по части слов подтверждением не считается.
  //
  // Мягкая ступень ищет по ЛЮБОМУ из слов запроса, и на живом реестре это
  // почти всегда мусор: «Синтез-газ» приводил к «Заглушке ПЭ 100 — ГАЗ»,
  // «Элементарная сера» — к «Краске художественной серой», «Адипиновая
  // кислота» — к «Молочной кислоте» и ещё двум сотням записей. На 662
  // продуктах живых графов так «находилось» 327 из 455.
  //
  // Отсеять это порогом редкости слова не вышло, и дело не в подборе числа:
  // верные и ложные совпадения по редкости ПЕРЕКРЫВАЮТСЯ. «хладон» — 72
  // записи и попадание верное, «легк» — 61 и мусор, «кумол» — 2 и верное,
  // «остаток» — 1 и мусор. Одной границы между ними не существует.
  //
  // Поэтому мягкие ступени больше не дают «найдено». Записи не выбрасываем —
  // возвращаем отдельным полем weak, чтобы разбор был виден и в аудите, и
  // потом в карточке отдельной строкой «возможно». Но число подтверждённых по
  // реестру должно означать «совпали все значимые слова», иначе узлу графа
  // приписываются чужие производители, чужой ОКПД2 и чужой регион.
  const loose = LOOSE_LEVELS.has(match);

  // Отбор по тому, ЧЕМ слово приходится названию записи.
  //
  // Совпадения всех значимых слов мало: для однословного запроса это
  // вырождается в «слово где-то в записи есть», и «Ноутбук» подтверждался
  // записью про влажные салфетки, годные в том числе для ноутбуков. Правило
  // подобрано замером на 128 подтверждениях с живых графов (см. --coverage):
  // из 21 отсеянного ни одно не оказалось нужным.
  const verdicts = kept.map((row, i) => verdict(picked.coverage?.[i]));

  // Препарат и лекарство — свидетельства второго сорта: вещество в них есть,
  // но продаётся другой товар. Засчитываем их, только если самого вещества в
  // реестре нет — решение заказчика. Поймано снимком: у «Хлорида натрия» 22
  // записи из 24 были растворами для инфузий, и код ОКПД2 выходил «Растворы
  // плазмозамещающие»; у перекиси водорода засчитывались пять «Спрейер-дез»,
  // у изопропанола — антибактериальное средство. Глифосат через «ТОРНАДО»
  // остаётся: самого глифосата в реестре нет, и препарат — всё, что есть.
  const pharmaQuery = isPharmaQuery([rawName, ...spellings]);
  // Спрашивают о самом растворе — «AdBlue», «Раствор мочевины AUS 32»: тогда
  // такие записи и есть ответ, а не второй сорт.
  const ureaQuery = [rawName, ...spellings].some((sp) => isUreaSolution(words(stemName(sp))));
  // То же для препарата пестицида: узел «Сера 400, КС» спрашивает о нём самом,
  // а «Средства защиты растений» — о препаратах вообще.
  const formQuery = [rawName, ...spellings].some(
    (sp) => isPesticideForm(sp) || namesPesticideClass(sp),
  );
  /** Препарат в ответ на вопрос о препарате — это и есть ответ. */
  const answersQuery = (v) =>
    Boolean((v.ureaSolution && ureaQuery) || (v.pesticideForm && formQuery));
  const secondaryWhy = kept.map((row, i) => {
    if (!verdicts[i].ok) return null;
    if (answersQuery(verdicts[i])) return null;
    if (verdicts[i].formulation) return "препарат, а вещество нашлось и само";
    if (!pharmaQuery && picked.coverage?.[i]?.medicine) {
      return "лекарство, а вещество нашлось и само";
    }
    return null;
  });
  const hasDirect = verdicts.some((v, i) => v.ok && !secondaryWhy[i]);
  const finalVerdicts = verdicts.map((v, i) =>
    hasDirect && secondaryWhy[i] ? { ok: false, why: secondaryWhy[i] } : v,
  );
  const confirmed = kept.filter((row, i) => finalVerdicts[i].ok);
  const rejected = kept.length - confirmed.length;

  // Разбор каждой записи — по запросу. Нужен, чтобы спорное подтверждение
  // разбирать не на глаз: видно, какая именно ветка confirms() его пропустила.
  // В обычном ответе этого нет: поле тяжёлое и интерфейсу не нужно.
  const explain = opts?.explain
    ? explainRows(picked, refused, finalVerdicts, dropped)
    : undefined;
  // Помечаем отдельно, когда вещество нашлось ТОЛЬКО в составе препарата:
  // ОКПД2 у такой записи пестицидный, а не глифосатный, и в карточке это
  // должно быть видно.
  // Препарат — по дозировке в скобке или по решению отбора: мочевинный
  // раствор для дизелей скобки с дозировкой не имеет, а препаратом считается.
  // Спросили о самом препарате — пометка «вещество в составе» была бы
  // неправдой: узел и есть препарат.
  const onlyFormulation =
    confirmed.length > 0 &&
    confirmed.every((row) => {
      const i = kept.indexOf(row);
      const v = finalVerdicts[i];
      return (
        picked.coverage?.[i]?.parens === "formulation" ||
        Boolean(v?.formulation && !answersQuery(v))
      );
    });

  let result;
  if (!kept.length) {
    // Номер CAS — факт справочника, а не реестра: он есть и у вещества,
    // которого в ГИСП нет вовсе, и в карточке показывать его всё равно стоит.
    result = {
      ...empty,
      canon: known?.canon ?? null,
      cas: known?.cas ?? null,
      category,
      tnvedCategory,
    };
  } else if (!loose && !confirmed.length) {
    // Записи нашлись, но ни одна не про этот продукт. Разбор сохраняем: без
    // него в карточке было бы просто «нет в реестре», и понять, что именно
    // отбросили, стало бы нечем.
    result = {
      ...empty,
      canon: known?.canon ?? null,
      cas: known?.cas ?? null,
      category,
      tnvedCategory,
      weak: {
        match,
        entryCount: kept.length,
        sharedWords: picked.shared,
        rarestWord: null,
        rarestFreq: null,
        matchedAs: normalizeName(matchedAs) === normalized ? null : matchedAs,
        sample: kept[0]?.name ?? null,
        /** Совпало, но не с самим продуктом: слово попало в середину чужого названия. */
        offTarget: true,
      },
      // Разбор нужен и здесь: продукт, переставший находиться, — первое, что
      // смотрят в снимке, и без разбора не видно, какой запрет его снял.
      ...(explain ? { explain } : {}),
    };
  } else if (loose) {
    // Самое редкое из совпавших слов оставляем в разборе: по нему сразу
    // видно, за что зацепились — за название вещества или за «кислоту».
    const freqs = picked.shared
      .map((s) => ({ stem: s, df: docFreq(conn, s) }))
      .sort((a, b) => a.df - b.df);
    result = {
      ...empty,
      canon: known?.canon ?? null,
      cas: known?.cas ?? null,
      category,
      tnvedCategory,
      weak: {
        match,
        entryCount: kept.length,
        sharedWords: picked.shared,
        rarestWord: freqs[0]?.stem ?? null,
        rarestFreq: freqs[0]?.df ?? null,
        matchedAs: normalizeName(matchedAs) === normalized ? null : matchedAs,
        // Запись в порядке выдачи индекса, а не по алфавиту: показывать надо
        // ту, за которую зацепились.
        sample: kept[0]?.name ?? null,
      },
    };
  } else {
    // Запись, которая решает судьбу продукта при любом пороге: ему достаточно
    // ОДНОЙ прошедшей записи, значит смотреть надо на самую убедительную —
    // ту, где совпадение началось раньше всего, а при равенстве покрыло
    // больше. Именно её и надо сравнивать с будущим порогом.
    const shares = picked.coverage ?? [];
    const leader = shares.length
      ? shares.reduce((a, b) =>
          b.at < a.at || (b.at === a.at && b.share > a.share) ? b : a,
        )
      : null;

    result = {
      // Сводку считаем по ПРОШЕДШИМ отбор записям, а не по всему найденному:
      // иначе производители, регионы и ОКПД2 приехали бы из отброшенных.
      ...summarize(confirmed, spellings),
      tnvedCategory,
      found: true,
      match,
      sharedWords: picked.shared,
      // Нашли под другим названием — скажем, под каким: иначе в карточке
      // непонятно, почему на «ПЭНД» приехали записи про полиэтилен.
      matchedAs: normalizeName(matchedAs) === normalized ? null : matchedAs,
      canon: known?.canon ?? null,
      cas: known?.cas ?? null,
      /** Сколько записей отбор отбросил как «слово попало в чужое название». */
      rejected,
      /** Вещество нашлось только в составе препарата — ОКПД2 у записи чужой. */
      viaFormulation: onlyFormulation,
      //
      // Продукту довольно ОДНОЙ убедительной записи, поэтому каждое основание
      // ищем по всем оставленным и называем запись, которая его дала: иначе
      // по отчёту не понять, за счёт чего продукт удержался.
      coverage: leader
        ? {
            share: leader.share,
            at: leader.at,
            name: leader.name,
            rowWords: leader.rowWords,
            matchedWords: picked.shared.length,
            records: shares.length,
            head: shares.find((s) => s.at === 0)?.name ?? null,
            parens: shares.find((s) => s.parens === "synonym")?.name ?? null,
            pair: shares.find((s) => nearPair(s))?.name ?? null,
            // Второе слово названия засчитываем, только если совпадение
            // объяснило заметную часть записи: «Противостаритель 6PPD М» и
            // «Термопластичные полиуретаны "Пикопан"» — это сам продукт с
            // категорией или прилагательным впереди. А «Ароматизатор воздуха
            // картонный Grass» при том же месте покрывает вчетверо меньше.
            second:
              shares.find((s) => s.at === 1 && s.strong >= 1 && s.share >= 1 / 3)
                ?.name ?? null,
            // Препаративная форма: вещество названо в составе, с дозировкой.
            formulation: shares.find((s) => s.parens === "formulation")?.name ?? null,
          }
        : null,
      ...(explain ? { explain } : {}),
    };
  }

  // Кэш растёт только на новых названиях; когда упрётся в предел — начинаем
  // заново, вытеснять по одному тут нечего оптимизировать.
  if (!opts?.explain) {
    if (cache.size >= CACHE_LIMIT) cache.clear();
    cache.set(normalized, result);
  }

  return result;
}

/**
 * Сложное прилагательное через дефис: «изобутилен-изопреновый».
 *
 * Такое слово называет не вещество, а его происхождение, и первая половина
 * отдельным веществом не является. Различаем по второй половине: если она
 * прилагательное — перед нами сложное определение, а если существительное
 * («н-бутан», «орто-ксилол»), то это приставка номенклатуры, и слово целое.
 */
const COMPOUND_MODIFIER =
  /([а-яё]{3,})-([а-яё]{3,}(?:ый|ий|ой|ая|яя|ое|ее|ые|ие|ого|его|ому|ему|ым|им|ых|их|ую|юю))(?![а-яё])/gi;

/**
 * Сложное прилагательное в названии записи совпадает с запросом целиком или
 * никак.
 *
 * «Бутилкаучук (изобутилен-изопреновый каучук)» — это каучук. Завод продаёт
 * каучук, а не изобутилен, и подставлять его в ответ на «Изобутилен» нельзя.
 * Сополимерные каучуки названы именно так, поэтому случай не единичный:
 * бутадиен-стирольный, этилен-пропиленовый и далее по списку.
 *
 * Раньше отсюда выбрасывалась только ПЕРВАЯ половина, и вторая совпадала сама
 * по себе. Снимок показал, чем это кончается: «Селитра известково-аммиачная»
 * — другое удобрение, аммиачная селитра с известняком, — превращалась в
 * «Селитра аммиачная» и подтверждала аммиачную селитру. Сложное слово
 * называет сочетание, и одна его половина — не то же самое, что целое.
 *
 * Поэтому: обе половины есть в запросе — слово остаётся двумя словами и
 * совпадает («Пропан-бутановая смесь» ↔ «Смесь пропано-бутановая»). Нет хотя
 * бы одной — половины склеиваются в слово, которое не совпадёт ни с чем.
 */
function bindCompounds(name, queryStems) {
  return String(name ?? "").replace(COMPOUND_MODIFIER, (whole, first, second) => {
    const both =
      isNomenclaturePrefix(first) ||
      (queryStems.has(stemWord(normalizeName(first))) &&
        queryStems.has(stemWord(normalizeName(second))));
    return both ? ` ${first} ${second} ` : ` ${first}${second} `;
  });
}

/**
 * Приставки номенклатуры: «цис-изопреновый», «трет-бутиловый», «изо-».
 *
 * Это не половина сочетания, а уточнение строения: «Каучук синтетический
 * цис-изопреновый СКИ-3» — изопреновый каучук и есть. Правило «целиком или
 * никак» их склеивало, и снимок показал цену: «Изопреновый каучук» потерял
 * семь записей СКИ-3 и СКИ-5 из одиннадцати.
 */
const NOMENCLATURE_PREFIXES = new Set([
  "цис", "транс", "трет", "втор", "изо", "нео", "орто", "мета", "пара",
  "альфа", "бета", "гамма", "дельта", "омега", "эндо", "экзо", "син", "анти",
  "мезо", "эритро", "трео", "сим", "асим", "рац",
]);

function isNomenclaturePrefix(part) {
  return NOMENCLATURE_PREFIXES.has(normalizeName(part));
}

/**
 * Сложное прилагательное, у которого с запросом совпала только одна половина:
 * «известково-аммиачная» при запросе «Аммиачная селитра». Для объяснения
 * отказа — см. bindCompounds.
 */
function halfCompound(name, queryStems) {
  for (const m of String(name ?? "").matchAll(COMPOUND_MODIFIER)) {
    if (isNomenclaturePrefix(m[1])) continue;
    const first = queryStems.has(stemWord(normalizeName(m[1])));
    const second = queryStems.has(stemWord(normalizeName(m[2])));
    if (first !== second) return m[0];
  }
  return null;
}

/**
 * Слова, которые строгая ступень потребовала у индекса. Их же должна
 * признать в записи сверка — иначе индекс нашёл запись по слову, которое
 * стоит там не в том качестве (см. keepBestOverlap).
 *
 * Мягкие ступени ищут по любому из слов, требовать с них нечего.
 */
function requiredStems(spelling, level) {
  const normalized = normalizeName(spelling);
  const list =
    level === "all-words"
      ? words(normalized).map(stemWord)
      : level === "core-words"
        ? coreWords(normalized).map(stemWord)
        : null;
  return list ? new Set(list.filter((w) => !STOP_WORDS.has(w))) : null;
}

/**
 * В скольких записях реестра встречается слово.
 *
 * Считается по полнотекстовому индексу, один раз на слово и на всё время
 * работы: слова запросов повторяются от продукта к продукту, а база между
 * переоткрытиями не меняется.
 */
const dfCache = new Map();
function docFreq(conn, stem) {
  const cached = dfCache.get(stem);
  if (cached !== undefined) return cached;
  let n = 0;
  try {
    // Тем же термином, что и поиск: у «натри» в индексе есть и прежняя
    // основа «натр» (см. LEGACY_STEMS в normalize.js).
    n = conn
      .prepare("SELECT COUNT(*) AS n FROM products_fts WHERE products_fts MATCH ?")
      .get(ftsTerm(stem)).n;
  } catch {
    // Слово, которое индекс не принимает как запрос. Считаем редким: пусть
    // решает совпадение, а не сбой разбора.
    n = 0;
  }
  dfCache.set(stem, n);
  return n;
}

/**
 * Подтверждает ли запись продукт — по тому, чем совпавшее слово ей приходится.
 *
 * Правило подобрано замером на 128 подтверждениях с живых графов, а не на
 * глаз: попытка отсеять мусор порогом доли покрытия провалилась (верные и
 * ложные совпадения по ней перекрываются: «Полиэтилен высокого давления
 * 15803-020» — те же 20%, что у мусора). Разделяет не пропорция, а МЕСТО:
 * из 127 подтверждений 89 совпали первым же словом записи, и все верные,
 * кроме одного.
 *
 * Пять оснований, каждое проверено на отсеве:
 *   1. первое слово — «Полиэтилен высокого давления»;
 *   2. второе, если объяснило хотя бы треть записи, — «Противостаритель
 *      6PPD М», «Термопластичные полиуретаны "Пикопан"». Доля здесь нужна:
 *      «Ароматизатор воздуха картонный Grass» стоит на том же месте, но
 *      покрывает вчетверо меньше;
 *   3. короткая скобка сразу за продуктом — в реестре это второе имя:
 *      «Изопропилбензол (кумол)»;
 *   4. два и более значимых слова в начале, стоящие РЯДОМ, — «Фракция
 *      альфа-олефинов C₈». Рядом — обязательно: «Порошок молибдена,
 *      изготовленный методом водородного восстановления триоксида молибдена»
 *      проходил как триоксид молибдена — «молибдена» стоит вторым, а
 *      «триоксида» в хвосте, где названо сырьё, а не продукт;
 *   5. состав с дозировкой в первой скобке — «ТОРНАДО, ВР (360 г/л
 *      глифосата к-ты)». По решению заказчика это присутствие вещества в
 *      реестре, но помечается отдельно: ОКПД2 у такой записи пестицидный.
 *
 * Что отсеивается: «Ноутбук» → «Салфетки влажные … для ноутбуков», «Сорбит» →
 * питательная среда, «Платина» → «Грунтовка НИПОЛ ПЛАТИНА», «Метилэтилкетон»
 * → «Ткань прорезиненная МЭК». Двадцать одна запись на живых графах, и ни
 * одной нужной среди них.
 */
function confirms(c) {
  return verdict(c).ok;
}

/**
 * Решение отбора по записи — вместе с основанием, словами.
 *
 * Основание нужно не самому отбору, а тому, кто его проверяет. Снимок до и
 * после показывает, какие записи ушли и какие пришли, а по одному названию не
 * сказать, почему: «Средство дезинфицирующее ОЗАЛИЗ (изопропанол)» ушла по
 * запрету или потому, что поиск перестал её находить? Решение и основание
 * считаются в одном месте, чтобы объяснение не разошлось с отбором.
 */
function verdict(c) {
  const v = baseVerdict(c);
  if (!v.ok || v.formulation) return v;
  // Основание пишем с пометкой: в снимке «+ первое слово» у препарата
  // выглядело бы как находка самого вещества.
  //
  // Мочевинный раствор для дизелей («Мочевина восстановитель оксидов азота
  // AUS 32», «Мочевина UNIX AdBlue SCR») — не карбамид, а товар из него.
  // Решение заказчика (сентябрь 2026): считать как препарат — только если
  // самого карбамида в реестре нет.
  if (c?.ureaSolution) {
    return { ...v, why: `препарат: ${v.why}`, formulation: true, ureaSolution: true };
  }
  // Препаративная форма пестицида, названная по веществу: «Сера 400, КС
  // (фунгицид)». Решение то же, что для скобки с дозировкой.
  if (c?.pesticideForm) {
    return { ...v, why: `препарат: ${v.why}`, formulation: true, pesticideForm: true };
  }
  return v;
}

function baseVerdict(c) {
  if (!c) return { ok: false, why: "нет разбора" };
  // Индекс нашёл запись по слову, которого сверка в ней не признаёт: «40» не
  // при своём слове, половина сложного прилагательного. Сильнее всех
  // оснований: записи не хватает слова, которое искали.
  if (c.incomplete) return { ok: false, why: c.incomplete };
  // Запись про СОЕДИНЕНИЕ этого вещества, а не про него само. Запрет сильнее
  // всех оснований ниже: «Закись азота» начинается со второго слова и
  // покрывает половину названия, то есть проходила бы как «второе слово».
  if (c.foreignClass) return { ok: false, why: "соединение вещества, а не оно само" };
  // Спросили «Натрий», а запись — «Натрия гипохлорит марки А» или «Кали едкое»:
  // элемент там назван только в косвенном падеже, то есть в имени соединения.
  if (c.elementCompound) return { ok: false, why: "соединение элемента, а не он сам" };
  // «Аммоний кальций нитрат» при запросе «Нитрат аммония»: двойная соль.
  if (c.otherElement) return { ok: false, why: `другое соединение: рядом «${c.otherElement}»` };
  // «О-Ксилол химически чистый» при запросе «Ксилол»: изомер, который
  // справочник знает отдельным веществом.
  if (c.otherIsomer) return { ok: false, why: `другое вещество: «${c.otherIsomer}»` };
  // Совпало одно лишь название класса. «Эфиры ЖК»: сокращение «ЖК» короче
  // трёх букв, ступень «значимые слова» его отбрасывает, и от запроса остаётся
  // «эфиры» — то есть КЛАСС соединений. После этого любой сложный эфир
  // реестра подтверждался первым же словом: заказчику доставались метил-трет-
  // бутиловый эфир и метилакрилат под видом эфиров жирных кислот.
  if (c.onlyClass) return { ok: false, why: "совпало одно название класса" };
  // Запись про набор или мерный реактив, а не про само вещество. Запрет
  // сильнее оснований ниже: «Стандарт-титры Янтарная кислота 0,1 Н» проходили
  // как «два значимых слова не дальше третьего».
  if (c.supplyForm) return { ok: false, why: "набор или мерный реактив" };
  // Изделие ИЗ вещества — «Стержни из фторопласта-4».
  if (c.madeOf) return { ok: false, why: "изделие «из» вещества" };
  // Продукт, содержащий вещество, — «Гуашь "Белила цинковые"», — или изделие
  // из него, названное прежде вещества: «Пакет ПНД (полиэтилен низкого
  // давления)». Уступает препаративной форме: её считать присутствием —
  // решение заказчика (но только когда самого вещества нет, см. lookupProduct).
  if (c.productBefore && c.parens !== "formulation") {
    return { ok: false, why: "изделие или продукт с веществом" };
  }
  if (c.at === 0) return { ok: true, why: "первое слово" };
  if (c.at === 1 && c.strong >= 1 && c.share >= 1 / 3) return { ok: true, why: "второе слово" };
  if (c.parens === "synonym") return { ok: true, why: "второе имя в скобках" };
  if (nearPair(c)) return { ok: true, why: "два слова рядом" };
  if (c.parens === "formulation") {
    return { ok: true, why: "в составе препарата", formulation: true };
  }
  return {
    ok: false,
    why: c.at === 1 ? "второе слово в длинном названии" : "вещество не в начале названия",
  };
}

/**
 * Разбор для отчётов: каждая найденная запись — с решением отбора и основанием.
 *
 * Сначала записи ответа, затем записи строгих попыток, где отбор не подтвердил
 * ничего. Без вторых запись, найденную и отброшенную запретом, было не отличить
 * от ненайденной: «Гуашь "Белила цинковые"» по написанию «Белила цинковые»
 * отбрасывалась целиком, в ответ не попадала — и в снимке выглядела так,
 * будто поиск перестал её находить.
 */
function explainRows(picked, refused, pickedVerdicts, dropped = []) {
  const out = [];
  const seen = new Set();
  const push = (row, cov, v = verdict(cov)) => {
    const key = row.id ?? `${row.name}\u0000${row.producer}`;
    if (seen.has(key)) return;
    seen.add(key);
    out.push({
      name: row.name,
      producer: row.producer,
      okpd2: row.okpd2,
      confirmed: v.ok,
      why: v.why,
      ...cov,
    });
  };
  // Записи ответа — с окончательным решением: препарат, отставленный потому,
  // что вещество нашлось и само, по одному разбору выглядел бы принятым.
  picked.rows.forEach((row, i) => push(row, picked.coverage?.[i], pickedVerdicts?.[i]));
  for (const t of refused) t.rows.forEach((row, i) => push(row, t.coverage?.[i]));
  // Отсеянные раньше вето — сравнением числа совпавших слов. Без них снимок
  // говорил об ушедшей записи «больше не находится поиском», хотя поиск её
  // находит, а отказ вполне определённый: «40» не при своём слове,
  // сложное слово совпало половиной.
  for (const d of dropped) push(d.row, {}, { ok: false, why: d.why });
  return out;
}

/**
 * Свести разборы нескольких написаний в один.
 *
 * Одна и та же запись может найтись по двум написаниям — «Медный купорос
 * (сульфат меди)» и по «сульфату меди», и по «медному купоросу». Считаем её
 * один раз, иначе записей в ответе стало бы больше, чем в реестре. Из двух
 * её разборов оставляем подтверждающий: подтвердило хоть одно написание —
 * значит, запись про это вещество.
 */
function combineTrials(trials) {
  const rows = [];
  const coverage = [];
  const shared = new Set();
  const seen = new Map();
  for (const t of trials) {
    t.rows.forEach((row, i) => {
      const cov = t.coverage?.[i];
      const key = row.id ?? `${row.name}\u0000${row.producer}`;
      const at = seen.get(key);
      if (at === undefined) {
        seen.set(key, rows.length);
        rows.push(row);
        coverage.push(cov);
      } else if (!confirms(coverage[at]) && confirms(cov)) {
        coverage[at] = cov;
      }
    });
    for (const s of t.shared ?? []) shared.add(s);
  }
  return { rows, coverage, shared: [...shared] };
}

/**
 * Основание 4: два значимых слова в начале — и стоят вместе.
 *
 * Последнее совпавшее слово не дальше, чем позволяет число совпавших, плюс
 * одно слово на уточнение между ними. Разбор без места последнего слова
 * (старый) ведёт себя как раньше.
 */
function nearPair(c) {
  if (!(c.strong >= 2 && c.at >= 0 && c.at <= 2)) return false;
  return (c.lastAt ?? c.at) <= c.at + c.strong;
}

