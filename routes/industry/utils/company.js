// routes/industry/utils/company.js
//
// Название организации из реестра — в читаемый вид.
//
// В выгрузке они записаны как в учредительных документах: заглавными и
// полностью — «ОБЩЕСТВО С ОГРАНИЧЕННОЙ ОТВЕТСТВЕННОСТЬЮ "ТЕХНОКЕРАМИКА"».
// В таблице такая строка занимает три строки и читается плохо, поэтому
// организационную форму сокращаем, а собственное имя приводим к обычному
// регистру: ООО «Технокерамика».
//
// Полное название при этом не выбрасывается: оно возвращается отдельным полем,
// чтобы интерфейс мог показать его подсказкой.

/**
 * Организационные формы. Порядок важен: длинные идут первыми, иначе
 * «ПУБЛИЧНОЕ АКЦИОНЕРНОЕ ОБЩЕСТВО» разобралось бы как «АКЦИОНЕРНОЕ ОБЩЕСТВО»
 * с лишним словом впереди.
 */
const FORMS = [
  ["публичное акционерное общество", "ПАО"],
  ["непубличное акционерное общество", "НАО"],
  ["открытое акционерное общество", "ОАО"],
  ["закрытое акционерное общество", "ЗАО"],
  ["акционерное общество", "АО"],
  ["общество с ограниченной ответственностью", "ООО"],
  ["индивидуальный предприниматель", "ИП"],
  ["производственный кооператив", "ПК"],
  ["сельскохозяйственный производственный кооператив", "СПК"],
  ["крестьянское фермерское хозяйство", "КФХ"],
  ["государственное унитарное предприятие", "ГУП"],
  ["федеральное государственное унитарное предприятие", "ФГУП"],
  ["муниципальное унитарное предприятие", "МУП"],
  ["федеральное казенное предприятие", "ФКП"],
  ["федеральное казённое предприятие", "ФКП"],
  ["научно-производственное объединение", "НПО"],
  ["научно-производственное предприятие", "НПП"],
  ["научно-производственный центр", "НПЦ"],
  ["научно-исследовательский институт", "НИИ"],
  ["опытно-конструкторское бюро", "ОКБ"],
  ["торговый дом", "ТД"],
  ["управляющая компания", "УК"],
];

// Уже сокращённые формы в начале названия: их трогать не надо.
const KNOWN_ABBR = new Set([
  "ООО", "АО", "ПАО", "ОАО", "ЗАО", "НАО", "ИП", "ПК", "СПК", "КФХ",
  "ГУП", "ФГУП", "МУП", "ФКП", "НПО", "НПП", "НПЦ", "НИИ", "ОКБ", "ТД", "УК",
]);

/**
 * Формы внутри собственного имени: «ООО "НАУЧНО-ПРОИЗВОДСТВЕННОЕ ПРЕДПРИЯТИЕ
 * СИНТЕЗ"» читается заметно лучше как «ООО «НПП Синтез»».
 */
const INNER_FORMS = [
  ["научно-производственное объединение", "НПО"],
  ["научно-производственное предприятие", "НПП"],
  ["научно-производственный центр", "НПЦ"],
  ["научно-исследовательский институт", "НИИ"],
  ["опытно-конструкторское бюро", "ОКБ"],
  ["производственное объединение", "ПО"],
  ["торговый дом", "ТД"],
];

/**
 * Длинные названия, которые пишутся заглавными и должны такими остаться.
 *
 * Отличить в русском аббревиатуру от слова по написанию нельзя: «ТАИФ» и
 * «АЗОТ» выглядят одинаково. Короткие оставляем как есть по длине, а для
 * длинных исключений держим список — он пополняется по мере встречи.
 */
const KEEP_UPPER = new Set(["ЛУКОЙЛ", "РОСНЕФТЬ", "ТАТНЕФТЬ", "ЕВРАЗ", "РУСАЛ"]);

/** До какой длины слово считаем аббревиатурой и не трогаем. */
const ABBR_MAX = 5;

/**
 * Служебные и родовые слова: с большой буквы они выглядят чужеродно.
 *
 * «ГРУППА КОМПАНИЙ "ТИТАН"» читается как «Группа компаний "Титан"», а не
 * «Группа Компаний». Предлоги сюда же: «ДЛЯ» короче порога аббревиатуры и
 * без этого списка так и осталось бы заглавными.
 */
const LOWER_WORDS = new Set([
  // родовые слова в названии
  "компания", "компании", "компаний",
  "группа", "группы", "группе",
  "завод", "завода", "заводы",
  "комбинат", "комбината",
  "объединение", "объединения",
  "фабрика", "фабрики",
  "корпорация", "корпорации",
  "концерн", "концерна",
  "предприятие", "предприятия",
  "институт", "института",
  "центр", "центра",
  "производство", "производства",
  "акционерная", "акционерное", "акционерный",
  "производственная", "производственное", "производственный",
  "торговая", "торговое", "торговый",
  "управляющая", "научная", "научное", "научный",
  // предлоги и союзы
  "для", "и", "по", "на", "с", "со", "в", "во", "от", "до",
  "при", "над", "под", "им", "имени", "или", "а",
]);

function titleWord(word, first) {
  // Через дефис каждая часть отдельно: «РН-КОМСОМОЛЬСКИЙ» → «РН-Комсомольский».
  if (word.includes("-")) {
    return word
      .split("-")
      .map((part, i) => titleWord(part, first && i === 0))
      .join("-");
  }

  // Кавычки внутри имени сохраняем: «КОМПАНИЯ "АЗОТ"».
  const open = word.match(/^[«"\']+/)?.[0] ?? "";
  const close = word.match(/[»"\']+$/)?.[0] ?? "";
  const core = word.slice(open.length, word.length - close.length);

  if (!core) return word;

  // Родовое слово или предлог не в начале — строчными.
  if (!first && LOWER_WORDS.has(core.toLowerCase())) {
    return open + core.toLowerCase() + close;
  }

  if (core.length <= ABBR_MAX || KEEP_UPPER.has(core)) return word;

  return open + core[0] + core.slice(1).toLowerCase() + close;
}

/** Собственное имя организации в читаемый вид. */
function titleCase(name) {
  // Строка не заглавными — значит, её уже записали по-человечески.
  if (name !== name.toUpperCase()) return name;
  return name
    .split(/\s+/)
    .map((w, i) => titleWord(w, i === 0))
    .join(" ");
}

/**
 * Сокращённое название организации.
 *
 * Возвращает строку вида «ООО «Технокерамика»». Если форму опознать не вышло,
 * название возвращается как есть — придумывать за реестр нечего.
 */
function shortenCompany(raw) {
  const full = String(raw ?? "").trim();
  if (!full) return "";

  const lower = full.toLowerCase();
  const hit = FORMS.filter(([phrase]) => lower.startsWith(phrase)).sort(
    (a, b) => b[0].length - a[0].length,
  )[0];

  let form = null;
  let rest = full;

  if (hit) {
    form = hit[1];
    rest = full.slice(hit[0].length).trim();
  } else {
    // Уже сокращено: «ООО "Ромашка"» или «АО НПЗ».
    const first = full.split(/\s+/)[0].replace(/[«»"']/g, "");
    if (KNOWN_ABBR.has(first.toUpperCase())) {
      form = first.toUpperCase();
      rest = full.slice(full.indexOf(first) + first.length).trim();
    }
  }

  // Снимаем только внешнюю пару кавычек: внутренние принадлежат имени —
  // «НОВОМОСКОВСКАЯ АКЦИОНЕРНАЯ КОМПАНИЯ "АЗОТ"».
  rest = rest.replace(/^[«"']\s*/, "").replace(/\s*[»"']$/, "").trim();

  // В реестре встречается «ГРУППА КОМПАНИЙ "ТИТАН"» с одной внешней кавычкой
  // на две открывающие. После снятия внешней пары внутренняя остаётся без
  // закрывающей — дописываем, иначе имя выходит с висящей кавычкой.
  if ((rest.match(/"/g) ?? []).length % 2 === 1) rest += '"';

  // Форма внутри имени тоже сокращается.
  const inner = INNER_FORMS.filter(([phrase]) =>
    rest.toLowerCase().startsWith(phrase),
  ).sort((a, b) => b[0].length - a[0].length)[0];
  if (inner) rest = `${inner[1]} ${rest.slice(inner[0].length).trim()}`.trim();

  rest = titleCase(rest);

  if (!rest) return form ?? full;
  return form ? `${form} «${rest}»` : rest;
}

module.exports = { shortenCompany };
