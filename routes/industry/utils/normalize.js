// routes/industry/utils/normalize.js
//
// Приведение названий продуктов к виду, пригодному для поиска по реестру.
//
// Названия в графе и в реестре пишут по-разному: в графе — «Изобутилен» или
// «С4-фракция (бутаны и бутилены)», в реестре — «Изобутилен технический марки
// А». Поэтому сравниваем не строки целиком, а наборы слов, и спускаемся по
// лестнице всё более мягких запросов, пока что-нибудь не найдётся.

/** Слова, которые ничего не сужают в поиске. */
const STOP_WORDS = new Set([
  "и",
  "или",
  "в",
  "во",
  "на",
  "для",
  "из",
  "с",
  "со",
  "по",
  "от",
  "до",
  "при",
  "а",
  "же",
  "др",
  "прочие",
  "прочая",
  "другие",
]);

/**
 * Слова, которые в реестре есть почти у всего и потому не помогают отличить
 * один продукт от другого. Из «ядра» запроса их убираем.
 */
const GENERIC_WORDS = new Set([
  "технический",
  "техническая",
  "технические",
  "марки",
  "марка",
  "сорт",
  "сорта",
  "продукт",
  "продукция",
  "смесь",
  "прочий",
  // «Изопрен (мономер)» — это изопрен. Слово говорит, в какой форме вещество,
  // но самого вещества не меняет.
  //
  // ОСТОРОЖНО при пополнении списка. Слово отсюда считается НЕ НЕСУЩИМ
  // различия: «Пропан технический» сведётся к пропану. Если сюда попадёт
  // «вторичный», то «Полиэтилен (вторичный)» сольётся с первичным сырьём —
  // а это разные продукты. Годятся только слова про исполнение и качество,
  // но не про происхождение и состав.
  "мономер",
]);

/**
 * Латинские буквы, неотличимые на вид от кириллических.
 *
 * «Бисфенол A» с латинской A и «Бисфенол А» с кириллической — на экране одна
 * и та же строка, а для программы разные, и такие продукты не сходятся
 * никогда. Отладить это глазами невозможно: символы выглядят одинаково.
 * Приводим латинские к кириллическим — какая сторона победит, неважно, важно
 * что одинаково с обеих.
 */
const LOOKALIKES = {
  a: "а", c: "с", e: "е", k: "к", o: "о", p: "р", x: "х", y: "у",
  b: "в", h: "н", m: "м", t: "т",
};
const LOOKALIKE_RE = /[acekopxybhmt]/g;

/**
 * Свести неотличимые на вид буквы к одному написанию.
 *
 * Решаем по строке целиком, а не по слову: в «Бисфенол A» подменённая буква
 * стоит отдельным словом, и по слову её от настоящей латиницы не отличить.
 * Есть в строке кириллица — значит, название русское, и латинские двойники в
 * нём почти наверняка опечатка раскладки.
 *
 * Строку без кириллицы не трогаем вовсе: «naphtha», «AdBlue», «PET» — это
 * латиница по существу. Заодно это оставляет в покое «Co» — обозначение
 * кобальта не превращается в «СО», угарный газ.
 */
function foldLookalikes(lowercased) {
  if (!/[а-я]/.test(lowercased)) return lowercased;
  return lowercased.replace(LOOKALIKE_RE, (ch) => LOOKALIKES[ch] ?? ch);
}

/**
 * Нормализовать строку: нижний регистр, ё→е, всё кроме букв и цифр — в пробелы.
 *
 * Регистр и «ё» разъезжаются между выгрузкой и графом постоянно, а дефисы,
 * кавычки и скобки в названиях расставлены как попало.
 *
 * Двойников букв здесь НЕ сводим, хотя соблазн есть. Этой самой функцией
 * посчитаны name_norm и полнотекстовый индекс в базе реестра: поменяв её, мы
 * разойдёмся с тем, что уже записано, и точные совпадения перестанут
 * находиться до переимпорта всей выгрузки. Для сравнения названий между собой
 * есть foldLookalikes — там база ни при чём.
 */
function normalizeName(raw) {
  return String(raw ?? "")
    .toLowerCase()
    .replace(/ё/g, "е")
    .replace(/[^a-zа-я0-9]+/gi, " ")
    .trim()
    .replace(/\s+/g, " ");
}

/** Разбить нормализованное название на значимые слова. */
function words(normalized) {
  return normalized.split(" ").filter((w) => w && !STOP_WORDS.has(w));
}

/**
 * Окончания, по которым слово — определение, а не название вещества.
 *
 * «-ий» сюда НЕ входит, хотя прилагательных с ним полно: на него кончаются
 * названия элементов — магний, кремний, алюминий, литий, силиций. Потерять их
 * ради отсева «нового» было бы плохим разменом, и правило без «-ий» работает.
 */
const QUALIFIER_END =
  /(ый|ая|ое|ые|ой|ую|ым|ых|яя|ее|юю|ого|его|ому|ему)$/;

/**
 * Название состоит из одних определений и вещества не называет.
 *
 * Вещества называются существительными: бензол, аммиак, хлор. «Новый» и
 * «Серная» сами по себе вещества не называют — им нужно существительное
 * рядом.
 *
 * Зачем правило. Запрос «Новый» достаёт из реестра «Жироудалитель „Новый
 * Элемент“»: слово совпадает вторым и покрывает треть записи, а такое отбор
 * подтверждает. Правило отбора при этом верное — спросили не о том, и узел
 * получал чужого производителя с чужим ОКПД2.
 *
 * Замерено перед включением: из 788 написаний справочника под правило не
 * подпадает НИ ОДНО, как и ни одно название продукта с сохранённых графов.
 */
function isQualifierOnly(rawName) {
  const parts = words(normalizeName(rawName));
  return parts.length > 0 && parts.every((w) => QUALIFIER_END.test(w));
}

/**
 * «Ядро» названия: слова без общих для всего реестра. Для «С4-фракция (бутаны
 * и бутилены)» это [с4, фракция, бутаны, бутилены] — по ним ещё можно искать,
 * тогда как по всей строке целиком не найдётся ничего.
 */
function coreWords(normalized) {
  const all = words(normalized);
  const core = all.filter((w) => !GENERIC_WORDS.has(w) && w.length > 2);
  return core.length ? core : all;
}


/**
 * Русские окончания, которые отрезаем. Длинные идут первыми, иначе «ами»
 * потеряло бы хвост от «и».
 */
const ENDINGS = [
  "ами",
  "ями",
  "ого",
  "его",
  "ому",
  "ему",
  "ыми",
  "ими",
  "ах",
  "ях",
  "ов",
  "ев",
  "ий",
  "ый",
  "ой",
  "ей",
  "ая",
  "яя",
  "ое",
  "ее",
  "ые",
  "ие",
  "ом",
  "ем",
  "ам",
  "ям",
  "ую",
  "юю",
  "а",
  "я",
  "ы",
  "и",
  "у",
  "ю",
  "о",
  "е",
  "ь",
];

/** Сколько букв должно остаться после отсечения — иначе режем смысл. */
const MIN_STEM = 4;

/**
 * Грубое усечение окончания.
 *
 * Полноценная морфология здесь избыточна, а без неё «бутаны» из графа не
 * находили «бутан технический» из реестра: индекс сравнивает словоформы
 * буквально. Важно не «правильно», а одинаково с обеих сторон — отсекаем и при
 * построении индекса, и в запросе.
 */
function stemWord(word) {
  for (const end of ENDINGS) {
    if (word.length - end.length >= MIN_STEM && word.endsWith(end)) {
      return word.slice(0, -end.length);
    }
  }
  return word;
}

/** Строка целиком в усечённом виде — то, что лежит в полнотекстовом индексе. */
function stemName(rawOrNormalized) {
  const normalized = normalizeName(rawOrNormalized);
  return words(normalized).map(stemWord).join(" ");
}

/** Экранировать слово для FTS5: оно понимает кавычки как строгую фразу. */
function ftsTerm(word) {
  return `"${word.replace(/"/g, '""')}"`;
}

/**
 * Лестница запросов к полнотекстовому индексу — от строгого к мягкому.
 *
 * Каждая ступень помечена уровнем совпадения: он уходит в ответ, чтобы в
 * интерфейсе было видно, точное это попадание или похожее.
 */
function buildQueryLadder(rawName) {
  const normalized = normalizeName(rawName);
  if (!normalized) return [];

  // В индексе лежат усечённые слова — запрос строим из таких же.
  const all = words(normalized).map(stemWord);
  const core = coreWords(normalized).map(stemWord);
  const ladder = [];

  // Все слова разом — самое строгое, что умеет индекс.
  if (all.length) {
    ladder.push({ level: "all-words", query: all.map(ftsTerm).join(" AND ") });
  }

  // Без общих слов реестра: «изобутилен технический» → «изобутилен».
  const coreQuery = core.map(ftsTerm).join(" AND ");
  if (core.length && coreQuery !== ladder[0]?.query) {
    // Ступень помечается как ПОТЕРЯВШАЯ различие, когда «ядро» выбросило не
    // общее слово, а короткое. Разница решающая.
    //
    // Убрать «технический» из «Изобутилен технический» безопасно: слово ничего
    // не говорит о веществе, и остаток — оно само. А убрать «п» из «П-Ксилол»
    // значит потерять единственное, чем пара-изомер отличается от орто- и
    // мета-: все три сводятся к одному «ксилолу». Так же теряется «S» из
    // «(NH4)S» — остаётся «nh4», то есть любой аммоний, и сульфид аммония
    // подтверждался сульфатом.
    //
    // Сам отброс оставляем: по «ДНТ» и «ксилолу» находится то, чего иначе не
    // найти. Но помеченную ступень нельзя выдавать за строгую — см.
    // STRICT_LEVELS в store.js.
    const kept = new Set(core);
    const lossy = words(normalized).some(
      (w) => !kept.has(stemWord(w)) && !GENERIC_WORDS.has(w),
    );
    ladder.push({ level: "core-words", query: coreQuery, lossy });
  }

  // Любое из значимых слов. Составные названия вроде «С4-фракция (бутаны и
  // бутилены)» целиком в реестре не встречаются, но отдельные вещества из них —
  // встречаются; берём то, что нашлось, и честно помечаем совпадение частичным.
  if (core.length > 1) {
    ladder.push({ level: "partial", query: core.map(ftsTerm).join(" OR ") });
  }

  // Приставка: «полипропилен» найдёт «полипропиленовый».
  const longest = core.slice().sort((a, b) => b.length - a.length)[0];
  if (longest && longest.length >= 5) {
    ladder.push({ level: "prefix", query: `${ftsTerm(longest)}*` });
  }

  return ladder;
}

/** Символ элемента: заглавная, иногда строчная следом, иногда индекс. */
const ATOM = "[A-Z][a-z]?\\d*";
const ELEMENT_FORMULA = new RegExp(`^(?:${ATOM}|\\((?:${ATOM})+\\)\\d*)+$`);

/**
 * Настоящая химическая формула: «Cl2», «Hg», «NaCl», «H2S2O7», «Ca(OH)2».
 *
 * Строгая нарочно. Формула — это ПЕРЕСКАЗ названия, а не другое вещество, и
 * на этом основано послабление в опознании: «Хлор (Cl2)» — тот же хлор.
 * Сокращения сюда пускать нельзя: «Каучук (SBR)» — это конкретный каучук, а
 * не каучук вообще, и такое послабление слило бы разные продукты.
 */
function isElementFormula(name) {
  const bare = String(name ?? "").replace(/\s+/g, "");
  return bare ? ELEMENT_FORMULA.test(bare) : false;
}

/**
 * Формула или обозначение латиницей: сверх формул ещё «PET», «2,4-D», «L-SBR».
 *
 * Мягче, чем isElementFormula, и годится только там, где надо отличить
 * «написано не по-русски, но осмысленно» от английского слова.
 */
function looksLikeFormula(name) {
  const bare = String(name ?? "").replace(/\s+/g, "");
  if (!bare) return false;
  if (ELEMENT_FORMULA.test(bare)) return true;
  return /^[A-Z0-9,.()\-]+$/.test(bare);
}

