/**
 * Пояснения к полям, которым мало подписи: единицы, год, доли. Цифры
 * объёмов модель охотно выдумывает — прямо разрешаем написать «нет данных».
 */
function hintsBlock(keys) {
  const lines = keys
    .filter((k) => FIELD_HINTS[k])
    .map((k) => `- ${labelsFor.all[k]} — ${FIELD_HINTS[k]}.`);
  if (!lines.length) return "";
  return (
    "\n\nПояснения к полям:\n" +
    lines.join("\n") +
    "\nЕсли надёжных цифр нет, так и напиши — не придумывай."
  );
}

/**
 * Промпт по умолчанию — тот же, что собирает интерфейс
 * (src/prompts/fillCardPrompts.ts): вступление, поля и пояснения к ним.
 */
function buildFillCardSystemPrompt({ nodeType, productName = "" }) {
  const tail = productName
    ? `\n\nДОПОЛНИТЕЛЬНО:\n- Целевой продукт (если упоминается) соответствует: ${productName}.`
    : "";
  const labels = labelsFor(nodeType);
  const keys = Object.keys(labels);
  const fields = keys.map((k) => `${labels[k]}:\n...`).join("\n\n");
  const isTransformation = nodeType === "transformation";
  const intro = isTransformation ? TRANSFORMATION_INTRO : PRODUCT_INTRO;
  const prefix = isTransformation
    ? "Верни ответ строго в таком виде:"
    : "Нужно вернуть ответ строго в таком виде:";
  return `${intro}\n\n${prefix}\n\n${fields}${hintsBlock(keys)}${tail}`;
}

function buildFillCardUserPrompt({ nodeType, inputText }) {
  if (nodeType === "transformation") {
    return `
Ниже передана производственная цепочка или описание цепочки.

Нужно:
- взять отправленный узел;
- составить по нему расширенное технологическое описание;
- использовать весь доступный контекст цепочки;
- опираться на инженерную и промышленную логику процесса.

Входные данные:
${inputText}
`.trim();
  }

  const labels = labelsFor("product");
  const fieldList = Object.keys(labels)
    .filter((k) => k !== "product_name")
    .map((k) =>
      k === "product_type"
        ? `- ${labels[k]}:\n  сырьё / промежуточный продукт / конечный продукт / побочный продукт / отход производства`
        : `- ${labels[k]}`,
    )
    .join("\n");

  return `
Ниже передана производственная цепочка или описание цепочки.

Нужно:
- взять отправленный узел;
- составить по нему расширенное описание;
- использовать весь доступный контекст цепочки;
- опираться на инженерную и промышленную логику процесса.

Поля, которые нужно заполнить:
${fieldList}

Входные данные:
${inputText}
`.trim();
}

