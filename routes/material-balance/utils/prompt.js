/**
 * Модель всегда считает на 1 т сырья (P1): пересчёт на любое количество и
 * единицу делает клиент — массы пропорциональны. Так один расчёт годится для
 * любого количества, и база переиспользуется целиком.
 */
const BASIS_KG = 1000;

/** Описание узла в промпт: без разметки и не длиннее абзаца. */
function brief(text, max = 600) {
  const plain = String(text || "")
    .replace(/[#*_`>]+/g, " ")
    .replace(/\s+/g, " ")
    .trim();
  return plain.length > max ? `${plain.slice(0, max - 1).trimEnd()}…` : plain;
}

const quoted = (name) => `«${String(name || "").trim()}»`;

/**
 * Обозначения узлов для модели и обратно: P1 — сырьё (исходный продукт
 * пары), P2 — продукт (целевой), P3… — остальные входы и выходы
 * преобразования, T1 — само преобразование.
 *
 * ID узлов графа модели не отдаём: они длинные, и модель их коверкает. По
 * коротким обозначениям сервер и клиент находят узлы обратно; ролей хватает,
 * чтобы применить расчёт и на другом графе с теми же продуктами.
 */
function buildRefs({ transformation, basis, target, inputs = [], outputs = [] }) {
  const refs = [
    { ref: "P1", name: String(basis.name).trim(), role: "basis" },
    { ref: "P2", name: String(target.name).trim(), role: "target" },
  ];
  const taken = new Set([basis.id ?? basis.name, target.id ?? target.name].map(String));
  let n = 3;
  const add = (list, role) => {
    for (const p of list) {
      const key = String(p?.id ?? p?.name ?? "");
      const name = String(p?.name || "").trim();
      if (!name || taken.has(key)) continue;
      taken.add(key);
      refs.push({ ref: `P${n++}`, name, role });
    }
  };
  add(inputs, "input");
  add(outputs, "output");
  refs.push({ ref: "T1", name: String(transformation.name).trim(), role: "transformation" });
  return refs;
}

/** Значения плейсхолдеров по запросу клиента. */
function buildVars(input, refs) {
  const byRole = (role) => refs.filter((r) => r.role === role);
  const ref = (r) => `${r.ref} ${quoted(r.name)}`;
  const [p1, p2] = refs;
  const t1 = refs.find((r) => r.role === "transformation");

  const selected = [
    [p1, input.basis],
    [p2, input.target],
  ]
    .map(([r, node]) => {
      const about = brief(node?.description);
      return `- ${r.ref} — ${r.name}.${about ? ` ${about}` : ""}`;
    })
    .join("\n");

  const ins = [p1, ...byRole("input")];
  const outs = [p2, ...byRole("output")];
  const techAbout = brief(input.transformation?.description);
  const context = [
    `Активный маршрут: ${ref(p1)} → ${t1.ref} ${quoted(t1.name)} → ${ref(p2)}.`,
    `Преобразование ${t1.ref} ${quoted(t1.name)}${techAbout ? `: ${techAbout}` : "."}`,
    `Все входы ${t1.ref} на графе: ${ins.map(ref).join("; ")}.`,
    `Все выходы ${t1.ref} на графе: ${outs.map(ref).join("; ")}.`,
    "Других стадий в выбранном участке нет: продукты вне этого преобразования в расчёт не входят.",
  ].join("\n");

  return {
    "<<<SELECTED_PRODUCTS>>>": selected,
    "<<<GRAPH_CONTEXT>>>": context,
    "<<<BASIS>>>": `${ref(p1)}: 1 т (${BASIS_KG} кг).`,
    "<<<KNOWN_DATA>>>": String(input.knownData || "").trim() || "Нет.",
    "<<<SERVER_SOURCE_CHECKS>>>":
      "Не передавались: серверная загрузка источников не выполнялась.",
  };
}

/** Подставить значения в шаблон (свой или по умолчанию). */
function fillPrompt(template, vars) {
  let out = String(template || "");
  for (const [key, value] of Object.entries(vars)) {
    out = out.split(key).join(value);
  }
  return out;
}

