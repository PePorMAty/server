/**
 * Единицы количества сырья. Промпт знает «кг» и «т» — тысячи тонн уходят
 * модели тоннами.
 */
const UNIT_KG = { кг: 1, т: 1000, "тыс. т": 1_000_000 };
const UNITS = Object.keys(UNIT_KG);

/** Описание узла в промпт: без разметки и не длиннее абзаца. */
function brief(text, max = 600) {
  const plain = String(text || "")
    .replace(/[#*_`>]+/g, " ")
    .replace(/\s+/g, " ")
    .trim();
  return plain.length > max ? `${plain.slice(0, max - 1).trimEnd()}…` : plain;
}

const quoted = (name) => `«${String(name || "").trim()}»`;

/** Число для промпта: без разрядов, с запятой — «2,5», «5000». */
const num = (v) => String(Number(v.toPrecision(12))).replace(".", ",");

/**
 * Количество опорного сырья: { amount, unit, kg }. Неверное — null.
 */
function basisAmount(amount, unit) {
  const v = Number(amount);
  if (!Number.isFinite(v) || v <= 0 || v > 1e12 || !UNIT_KG[unit]) return null;
  return { amount: v, unit, kg: v * UNIT_KG[unit] };
}

/**
 * Обозначения узлов для модели и обратно. P1 — опорное сырьё (на него задано
 * количество), P2 — первый выбранный продукт, дальше остальное сырьё,
 * остальные выбранные продукты и невыбранные выходы; T1 — само
 * преобразование.
 *
 * Роли: basis — опорное сырьё, input — прочее сырьё, target — выбранный
 * продукт, output — выход, который человек не выбрал. P1 и P2 — как у
 * прежнего расчёта пары «сырьё → продукт»: такой расчёт — частный случай
 * нового, с одним продуктом, и клиенты обоих видов читают записи друг друга.
 *
 * ID узлов модели не отдаём: они длинные, и модель их коверкает. Они лежат в
 * refs (id) — клиент по ним кладёт свежий расчёт на свои узлы; на другом
 * графе узлы находятся по названиям (matchRefs).
 */
function buildRefs({ transformation, inputs, outputs, targets, basis }) {
  const refs = [];
  const add = (node, role) =>
    refs.push({
      ref: `P${refs.length + 1}`,
      id: node.id,
      name: String(node.name).trim(),
      role,
    });
  const ref = inputs.find((n) => n.id === basis.id);
  const chosen = outputs.filter((n) => targets.includes(n.id));
  add(ref, "basis");
  add(chosen[0], "target");
  for (const n of inputs) if (n !== ref) add(n, "input");
  for (const n of chosen.slice(1)) add(n, "target");
  for (const n of outputs) if (!targets.includes(n.id)) add(n, "output");
  refs.push({
    ref: "T1",
    id: transformation.id,
    name: String(transformation.name).trim(),
    role: "transformation",
  });
  return refs;
}

const isInput = (r) => r.role === "basis" || r.role === "input";
const isTarget = (r) => r.role === "target";

/** Значения плейсхолдеров по запросу клиента. */
function buildVars(input, refs) {
  const nodes = new Map([...input.inputs, ...input.outputs].map((n) => [n.id, n]));
  const ref = (r) => `${r.ref} ${quoted(r.name)}`;
  const t1 = refs.find((r) => r.role === "transformation");
  const p1 = refs[0];
  const ins = refs.filter(isInput);
  const chosen = refs.filter(isTarget);
  const rest = refs.filter((r) => r.role === "output");

  const line = (r, what) => {
    const about = brief(nodes.get(r.id)?.description);
    return `- ${r.ref} — ${r.name} (${what}).${about ? ` ${about}` : ""}`;
  };
  const selected = [
    ...ins.map((r) => line(r, r.role === "basis" ? `вход ${t1.ref}, опорный` : `вход ${t1.ref}`)),
    ...chosen.map((r) => line(r, `выход ${t1.ref}`)),
  ].join("\n");

  const techAbout = brief(input.transformation?.description);
  const context = [
    `Преобразование ${ref(t1)}${techAbout ? `: ${techAbout}` : "."}`,
    `Активный маршрут: ${ins.map(ref).join(" + ")} → ${ref(t1)} → ${chosen.map(ref).join(" + ")}.`,
    `Все входы ${t1.ref} на графе: ${ins.map(ref).join("; ")} — все выбраны.`,
    rest.length
      ? `Выходы ${t1.ref} на графе: выбраны ${chosen.map(ref).join("; ")}; не выбраны ${rest.map(ref).join("; ")}.`
      : `Все выходы ${t1.ref} на графе: ${chosen.map(ref).join("; ")} — все выбраны.`,
    "Других стадий в выбранном участке нет: продукты вне этого преобразования в расчёт не входят.",
  ].join("\n");

  const b = input.basis;
  const shown = b.unit === "тыс. т" ? `${num(b.kg / 1000)} т` : `${num(b.amount)} ${b.unit}`;
  const others = ins.filter((r) => r !== p1);
  const basis = [
    `${ref(p1)}: ${shown} (${num(b.kg)} кг).`,
    ...(others.length
      ? [
          `Количества остальных входов (${others.map(ref).join("; ")}) не заданы: рассчитай, сколько их требуется на это количество ${p1.ref}, по подтверждённым расходным соотношениям.`,
        ]
      : []),
  ].join("\n");

  return {
    "<<<SELECTED_PRODUCTS>>>": selected,
    "<<<GRAPH_CONTEXT>>>": context,
    "<<<BASIS>>>": basis,
    "<<<KNOWN_DATA>>>": String(input.knownData || "").trim() || "Нет.",
    // Источники сервер пока не скачивает: первый и единственный запрос —
    // с пустым списком, как в примечании заказчика к промпту.
    "<<<SERVER_SOURCE_CHECKS>>>": "[] — серверная загрузка источников не выполнялась.",
  };
}

/** Подставить значения в шаблон (свой или по умолчанию). */
function fillPrompt(template, vars) {
  let out = String(template || "");
  for (const [key, value] of Object.entries(vars)) {
    out = out.split(key).join(value);
  }
  return out;
}

