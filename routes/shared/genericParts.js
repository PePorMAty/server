// routes/shared/genericParts.js
//
// Общее название узла или детали — «Двигатель», «Шасси», «Крылья»: такие
// есть у машины, самолёта и корабля, и само по себе название не говорит,
// какой это продукт. «Электроника и авионика», «Интерьер и сиденья» — тоже
// общие.
//
// Нужно в двух местах:
//   • построение шага вверх от изделия (routes/step/build.js) уточняет такой
//     узел изделием — «Двигатель (Автомобиль)»;
//   • коды моделью (routes/industry/codes.js): код общего названия зависит от
//     изделия, и переносить его на одноимённые узлы других графов нельзя —
//     двигатель машины получил бы код двигателя самолёта (2026-11-17).

const GENERIC_PART =
  /^(двигател[ьи]|мотор|электродвигател[ьи]|силовая установка|шасси|кузов|рама|крыл[оья]+|фюзеляж|оперение|винт|винты|редуктор|насос|насосы|генератор|аккумулятор|аккумуляторы|аккумуляторная батарея|трансмисси[яи]|коробка передач|подвеска|колеса|колёса|шины|салон|интерьер|сиденья|электроника|электрооборудование|авионика|корпус|оборудование|комплектующие|компоненты|узлы|агрегаты|детали|запчасти|приборы|система управления|топливная система)$/;

/** Название — одни общие слова деталей («Двигатель», «Шасси и подвеска»). */
function isGenericPart(name) {
  const parts = String(name || "")
    .toLowerCase()
    .replace(/ё/g, "е")
    .split(/\s+и\s+|,\s*/)
    .map((x) => x.trim())
    .filter(Boolean);
  return parts.length > 0 && parts.every((x) => GENERIC_PART.test(x));
}

/**
 * Общее название без уточнения изделием: «Двигатель» — да, «Двигатель
 * (Самолёт)» — нет, у него изделие названо.
 */
function isUnqualifiedGeneric(name) {
  const raw = String(name || "").trim();
  if (/\([^)]+\)\s*$/.test(raw)) return false;
  return isGenericPart(raw);
}

module.exports = { GENERIC_PART, isGenericPart, isUnqualifiedGeneric };
