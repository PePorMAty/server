// routes/tech-description/utils/prompt.js
//
// Промпт «технологическое описание одного продуктового шага».
// Описывает ТОЛЬКО непосредственное преобразование входного продукта в выходной
// при добавлении одного продукта к цепочке ВНИЗ или ВВЕРХ.
//
// Шаблон редактируется на клиенте (карточка преобразования → вкладка
// «Технологическое описание»), поэтому подстановка переменных живёт здесь:
// пользователь правит текст, а плейсхолдеры остаются на месте и заполняются
// сервером из тела запроса.

// Разделитель system/user: всё до маркера — правила (instructions), всё от
// маркера — входные данные (input). Если пользователь удалил маркер из своего
// промпта, весь текст уходит одним пользовательским сообщением.
const TECH_DESCRIPTION_INPUT_MARKER = "Входные данные:";

const TECH_DESCRIPTION_PROMPT_TEMPLATE = `Ты — инженер-технолог и аналитик производственных цепочек. Составь краткое технологическое описание добавления одного продукта к существующей цепочке в заданном направлении: ВНИЗ или ВВЕРХ.

Сначала определи границы описываемого шага:

* ВНИЗ: существующий продукт является непосредственным входным сырьём, а дополнительный продукт — непосредственным выходом переработки.
* ВВЕРХ: дополнительный продукт является непосредственным входным сырьём, из которого получают существующий продукт.
* Независимо от направления описывай только непосредственное преобразование: входной продукт → выходной продукт.

Напиши 2–4 связных предложения только о данном продуктовом шаге. Укажи способ непосредственного преобразования входного продукта в выходной, основные операции, обеспечивающие его получение, и, если это прямо приведено во входных данных, существенные реагенты, катализаторы или условия процесса.

Ограничения:

* не описывай, как был получен входной продукт;
* не описывай дальнейшую переработку или применение выходного продукта;
* не переходи к другим уровням производственной цепочки;
* не пересказывай полную технологию производства;
* не добавляй новые продукты, побочные продукты или альтернативные маршруты, не относящиеся к заданному шагу;
* не представляй операции, оборудование, реагенты, катализаторы или технологические состояния как отдельные продукты;
* используй только предоставленные сведения, без внешних знаний и предположений;
* если технологических деталей недостаточно, опиши только подтверждённую связь между продуктами и не восполняй пробелы догадками;
* пиши только на русском языке.

Выведи только готовое описание из 2–4 предложений — без заголовка, списка, примечаний и пояснения выбранного направления.

${TECH_DESCRIPTION_INPUT_MARKER}

Направление построения цепочки:
<<<DIRECTION>>>

Существующий продукт, к которому добавляется шаг:
<<<CURRENT_PRODUCT>>>

Дополнительный продукт:
<<<ADDITIONAL_PRODUCT>>>

Существующая производственная цепочка:
<<<EXISTING_CHAIN>>>

Текстовые сведения о технологии и связи продуктов:
<<<PROCESS_DESCRIPTION>>>`;

function directionLabel(direction) {
  return direction === "up" ? "ВВЕРХ" : "ВНИЗ";
}

function stringifyChain(chain) {
  if (chain === null || chain === undefined) return "";
  if (typeof chain === "string") return chain.trim();
  try {
    return JSON.stringify(chain, null, 2);
  } catch {
    return String(chain);
  }
}

// Плейсхолдер → значение. Значение подставляем через функцию-replacer: иначе
// «$&» и подобные последовательности внутри описаний интерпретировались бы как
// спецсимволы замены.
function replaceAll(text, pattern, value) {
  return text.replace(pattern, () => value);
}

/**
 * Подставляет переменные в шаблон (свой или дефолтный).
 * Плейсхолдер направления принимается и в исходном виде из ТЗ
 * («<<<DIRECTION: ВНИЗ / ВВЕРХ>>>»), и в коротком «<<<DIRECTION>>>».
 */
function fillTechDescriptionPrompt(template, vars) {
  const {
    direction,
    currentProduct,
    additionalProduct,
    existingChain,
    processDescription,
  } = vars;

  const empty = "(нет данных)";
  let out = String(template || "");

  out = replaceAll(out, /<<<DIRECTION[^>]*>>>/g, directionLabel(direction));
  out = replaceAll(
    out,
    /<<<CURRENT_PRODUCT>>>/g,
    String(currentProduct || "").trim() || empty,
  );
  out = replaceAll(
    out,
    /<<<ADDITIONAL_PRODUCT>>>/g,
    String(additionalProduct || "").trim() || empty,
  );
  out = replaceAll(
    out,
    /<<<EXISTING_CHAIN>>>/g,
    stringifyChain(existingChain) || empty,
  );
  out = replaceAll(
    out,
    /<<<PROCESS_DESCRIPTION>>>/g,
    String(processDescription || "").trim() || empty,
  );

  return out;
}

/** Делит заполненный промпт на системную часть (правила) и пользовательскую
 *  (входные данные). Маркера нет — всё уходит пользовательским сообщением. */
function splitTechDescriptionPrompt(full) {
  const text = String(full || "");
  const idx = text.indexOf(TECH_DESCRIPTION_INPUT_MARKER);
  if (idx === -1) return { system: "", user: text.trim() };
  return {
    system: text.slice(0, idx).trim(),
    user: text.slice(idx).trim(),
  };
}

module.exports = {
  TECH_DESCRIPTION_PROMPT_TEMPLATE,
  TECH_DESCRIPTION_INPUT_MARKER,
  directionLabel,
  fillTechDescriptionPrompt,
  splitTechDescriptionPrompt,
  stringifyChain,
};
