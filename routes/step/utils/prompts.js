function stringifyExistingChain(chain) {
  if (chain === null || chain === undefined) return "[]";
  if (typeof chain === "string") return chain.trim() || "[]";
  try {
    return JSON.stringify(chain, null, 2);
  } catch {
    return String(chain);
  }
}

function formatBlocksForPrompt(blocks) {
  const arr = Array.isArray(blocks) ? blocks : [];
  return arr
    .map((b, i) => {
      const txt = String(b || "").trim();
      if (!txt) return null;
      const first = txt.split("\n", 1)[0].trim();
      if (/^Источник\s*\d+\s*:?\s*$/i.test(first)) return txt;
      return `Источник ${i + 1}\n\n${txt}`;
    })
    .filter(Boolean)
    .join("\n\n---\n\n");
}

/** Промпт обобщения по умолчанию — для окна «Редактировать промпт обобщения». */
function stepAggregateDefaults(direction = "down") {
  const isUp = direction === "up";
  return {
    system: isUp ? STEP_AGGREGATE_SYSTEM_UP : STEP_AGGREGATE_SYSTEM,
    template: isUp
      ? STEP_AGGREGATE_USER_TEMPLATE_UP
      : STEP_AGGREGATE_USER_TEMPLATE,
  };
}

/**
 * customSystem / customUser — промпт, правленый в окне построения. Плейсхолдеры
 * в правленом тексте заполняются так же, как в шаблоне по умолчанию: раньше
 * сервер подставлял туда только родословную, и модель получала «<<<BLOCKS>>>»
 * вместо текстов источников.
 */
function buildStepAggregatePrompts({
  productName,
  existingChain,
  blocks,
  ancestorProducts = [],
  direction = "down",
  customSystem = null,
  customUser = null,
}) {
  const blocksText = formatBlocksForPrompt(blocks);
  const chainText = stringifyExistingChain(existingChain);

  const lineageList = (Array.isArray(ancestorProducts) ? ancestorProducts : [])
    .map((s) => String(s || "").trim())
    .filter(Boolean);
  const lineageText = lineageList.length
    ? lineageList.map((a) => `- ${a}`).join("\n")
    : "(пусто — это первый шаг цепочки, петля невозможна)";

  // UP — зеркало DOWN: якорь становится ВЫХОДОМ, ищем входные прекурсоры.
  const defaults = stepAggregateDefaults(direction);
  const values = {
    TARGET_PRODUCT: String(productName || "").trim(),
    EXISTING_CHAIN: chainText || "[]",
    LINEAGE: lineageText,
    BLOCKS: blocksText,
  };
  // Значение — через функцию: «$&» и подобное в текстах источников иначе
  // читалось бы как шаблон замены.
  const fill = (text) =>
    String(text).replace(
      /<<<(TARGET_PRODUCT|EXISTING_CHAIN|LINEAGE|BLOCKS)>>>/g,
      (_, key) => values[key],
    );

  return {
    SYSTEM: fill(customSystem || defaults.system),
    USER_PROMPT: fill(customUser || defaults.template),
    lineageText,
  };
}

