// routes/step/utils/outputCheck.js
//
// Выход шага «вниз» — не продукт: проверка по тексту ответа и источникам.
//
// Живые прогоны 2026-11-03: от «Пиролизной жидкости» модель дала выход
// «Углеводороды» — класс веществ, а от «Полиэтилена низкой плотности» —
// пиролиз отходов в «Пиролизную жидкость»: источники нашлись только о
// вторичной переработке, и цепочка ушла в бионефть из биомассы. Правила
// промпта модель не убедили (prompt-check 2026-11-09: снова «Углеводороды»
// и «Нафта» из пиролиза отходов), поэтому, как с перепрыгиванием уровня,
// проверяет сервер и переспрашивает один раз в той же переписке.

const { mainStep } = require("./levelSkip");

/**
 * Класс веществ или неопределённый продукт процесса. Товарные фракции и
 * смолы с устоявшимся названием («Смола пиролиза», «Фракция C4») — продукты,
 * как и «углеводороды C5–C6» с указанием состава.
 */
const GENERIC =
  /^(смесь\s+)?(углеводород|ароматическ\S*\s+(соединени|углеводород)|кислородсодержащ|органическ\S*\s+(соединени|веществ)|продукт\S*\s+(реакци|пиролиз|крекинг|переработ)|жидк\S*\s+продукт|пиролизн\S*\s+(жидкост|масл)|смесь$)/i;

function isGeneric(name) {
  const n = String(name || "").trim();
  return GENERIC.test(n) && !/\d/.test(n);
}

/**
 * «Смесь X и Y» — названные продукты одной записью (prompt-check 2026-11-09:
 * «Смесь циклогексанола и циклогексанона» вопреки правилу промпта). Товарную
 * смесь («Смесь пропана и бутана») модель на дозапросе может оставить.
 */
const isMixture = (name) => /^смесь\s+\S.*\s+и\s+\S/i.test(String(name || "").trim());

/**
 * Название источника — про переработку отходов, а не самого продукта.
 * Только название: в описании любого источника есть строка «Побочные/отходы».
 */
const WASTE =
  /recycl|upcycl|рециклинг|вторичн\S*\s+(переработ|сырь|полимер)|переработк\S*\s+(отход|пластиков)|из\s+отход|waste|утилизац|end-of-life|post-consumer/i;

/**
 * Все источники шага — найденные в интернете и о переработке отходов
 * продукта. Разделы базы (origin: local) описывают производство — с ними
 * шаг не про отходы.
 */
function wasteOnly(sources) {
  const list = Array.isArray(sources) ? sources : [];
  return list.length > 0 && list.every((s) => s?.origin !== "local" && WASTE.test(String(s?.title || "")));
}

/**
 * Что не так с выходом основного шага: { kind: "waste" | "generic" |
 * "mixture", outputs, generic } или null. Пустой выход — уже тупик, переспрашивать незачем.
 */
function outputProblem(markdown, sources) {
  const outputs = mainStep(markdown)?.outputs ?? [];
  if (!outputs.length) return null;
  if (wasteOnly(sources)) return { kind: "waste", outputs, generic: [] };
  const generic = outputs.filter(isGeneric);
  if (generic.length) return { kind: "generic", outputs, generic };
  const mixtures = outputs.filter(isMixture);
  return mixtures.length ? { kind: "mixture", outputs, generic: mixtures } : null;
}

/** Дозапрос: что исправить и как — в той же переписке. */
function outputFollowUp(productName, problem) {
  const tail = "Верни ответ заново, целиком, по тому же шаблону.";
  if (problem.kind === "waste") {
    return [
      "Проверка сервера: шаг — переработка отходов, а не самого продукта.",
      `Все текстовые блоки — о переработке отходов «${productName}» (вторичная переработка, пиролиз, утилизация отслуживших изделий). По правилу «Переработка ОТХОДОВ продукта — не следующий шаг цепочки» оставь «Что производят» пустым, альтернатив по переработке отходов не выводи и напиши в «Примечаниях»: «описана только переработка отходов — вероятно, это конечный продукт».`,
      tail,
    ].join("\n\n");
  }
  if (problem.kind === "mixture") {
    return [
      "Проверка сервера: продукты смеси записаны одной строкой.",
      `«${problem.generic.join("», «")}» — по правилу «Если стадия даёт смесь названных продуктов… в «Что производят» — каждый названный продукт смеси» запиши каждый продукт отдельно, в именительном падеже (не «смесь»). Если смесь продают как самостоятельный товар под этим названием, оставь её как есть.`,
      tail,
    ].join("\n\n");
  }
  return [
    "Проверка сервера: выход шага — не продукт.",
    `«${problem.generic.join("», «")}» — класс веществ или неопределённый продукт процесса. По правилу «Выход — конкретный названный продукт» назови продукт, который по блокам получают из «${productName}» (топливо, бензол, смола с устоявшимся названием), или оставь «Что производят» пустым и объясни это в «Примечаниях».`,
    tail,
  ].join("\n\n");
}

/** Принимаем ответ на дозапрос, только если он исправил то, о чём спросили. */
function acceptOutputFollowUp(markdown, problem) {
  const main = mainStep(markdown);
  if (!main) return false;
  if (problem.kind === "waste") return main.outputs.length === 0;
  if (problem.kind === "mixture") return main.outputs.length > 0 && !main.outputs.some((o) => isMixture(o) || isGeneric(o));
  return !main.outputs.some(isGeneric);
}

module.exports = { outputProblem, outputFollowUp, acceptOutputFollowUp, isGeneric, isMixture, wasteOnly };
